#!/bin/sh
# СТРАЖ ШАБЛОНОВ: строковый литерал Go-шаблона не может быть разорван переносом.
# Подозрительна строка с НЕЧЁТным числом двойных кавычек:
#   чётное (включая 0) — кавычки закрыты на той же строке;
#   нечётное — литерал открыт и не закрыт (перенос внутри строки).
cd "$(dirname "$0")/.." || exit 1

fail=0
for f in internal/webpanel/templates/*.html; do
    out=$(awk '{ q = gsub(/"/, "&"); if (q % 2 == 1) print FNR ": " $0 }' "$f")
    if [ -n "$out" ]; then
        echo "РАЗОРВАННЫЙ ЛИТЕРАЛ в $f:"
        echo "$out"
        fail=1
    fi
done

[ "$fail" -eq 0 ] && echo "Шаблоны чисты."
exit $fail