// ============================================================================
// УТИЛИТА: ПРОВЕРКА НАЛИЧИЯ ПРАВИЛА В NETFILTER
// ============================================================================

// VerifyUfwRulePresence быстро проверяет наличие правила в Netfilter
// без блокирующих пауз. Делает строго ОДИН быстрый снимок брандмауэра.
//
// ПАРАМЕТРЫ:
//   - targetComment: уникальный комментарий-маркер правила для поиска
//   - shouldExist: true = правило должно существовать, false = должно отсутствовать
//
// ВОЗВРАЩАЕТ:
//   - true: если состояние правила соответствует ожиданию
//   - false: если состояние правила НЕ соответствует ожиданию
//
// ВАЖНО: Эта функция НЕ изменяет ничего. Только читает.
// ОБНОВЛЕНО В v6.2.2: Полный отказ от циклов и задержек.
// БЕЗ ИЗМЕНЕНИЙ В v8.0.1.
func VerifyUfwRulePresence(targetComment string, shouldExist bool) bool {
	// БЛОК 3.1: статус UFW получается через единый интерфейс исполнения команд.
	// Ошибка не игнорируется: если UFW недоступен, верификация невозможна.
	statusRes := sys.RunTimeout(5*time.Second, "ufw", "status")

	// Если команда не подтверждена, считаем правило неподтверждённым.
	// Это читерский, но безопасный fail-safe: лучше вернуть false,
	// чем поверить в несуществующее правило.
	if statusRes.Err != nil {
		// event=ufw.status_failed — машинный код сбоя чтения статуса.
		statusRes.LogWarnIfErr("TARPIT_SERVICE", "UFW_VERIFY", "event=ufw.status_failed")
		return false
	}

	// Выполняем контекстный поиск уникального комментария-маркера в таблице Netfilter.
	// Используем Stdout, а не сырой []byte.
	contains := containsWithBoundary(statusRes.Stdout, targetComment)

	// Правило должно существовать — и оно найдено.
	if shouldExist && contains {
		return true
	}

	// Правило должно отсутствовать — и оно не найдено.
	if !shouldExist && !contains {
		return true
	}

	// Состояние не совпало с ожиданием.
	return false
}

// containsWithBoundary — поиск подстроки с числовой границей: сразу после
// совпадения НЕ должно стоять цифры. Защищает от коллизии префиксов
// «Port 22» ⊂ «Port 2244». Сканирует ВСЕ вхождения: если первое упирается
// в цифру (чужой порт), ищем дальше до гранично-чистого совпадения.
func containsWithBoundary(haystack, needle string) bool {
	idx := 0
	for {
		pos := strings.Index(haystack[idx:], needle)
		if pos == -1 {
			return false
		}
		end := idx + pos + len(needle)
		if end >= len(haystack) || haystack[end] < '0' || haystack[end] > '9' {
			return true
		}
		idx = end
	}
}

// ============================================================================
// ПРОТОКОЛ УПРАВЛЕНИЯ ДЕГТЯРНОЙ ЯМОЙ (АДАПТЕР СОВМЕСТИМОСТИ)
// ============================================================================

// SetTarpitProtocol координирует жизненный цикл Дегтярной Ямы на порту 22.
// Является АДАПТЕРОМ СОВМЕСТИМОСТИ: сохраняет старый интерфейс для
// `armor.ExecuteArmorRoute("TARPIT", ...)`, но делегирует управление
// ловушкой в новый контроллер `tarpitctl`.
//
// АРХИТЕКТУРНОЕ РЕШЕНИЕ (v8.0.1):
//   - UFW-правила порта 22 управляются ЗДЕСЬ (домен `armor`)
//   - Инвентарь, демон, маркеры управляются через `tarpitctl`
//   - Прямые вызовы `systemctl` УБРАНЫ из этого файла
//   - Прямая запись маркеров УБРАНА из этого файла
//
// ПАРАМЕТРЫ:
//   - action: "ON" / "OFF" / "CHECK"
//
// ОБНОВЛЕНО В v8.0.1: Полная перепись функции.
func SetTarpitProtocol(action string) error {
	switch strings.ToUpper(action) {

	// =================================================================
	// TARPIT ON: Активация Дегтярной Ямы на порту 22
	// =================================================================
	//
	// ПОРЯДОК ОПЕРАЦИЙ:
	//   1. Ядерный предохранитель: проверка рокировки
	//   2. Вытеснение брони: деактивация лимитера на порту 22
	//   3. Подготовка UFW: выжигание старых правил, создание нового
	//   4. Делегирование в tarpitctl: запись в инвентарь, запуск демона
	//
	// ВАЖНО: UFW подготавливается ДО активации ловушки.
	// Если бот не может достичь порта 22 через брандмауэр,
	// ловушка бесполезна. Поэтому сначала открываем шлюз, потом ловим.
	// =================================================================
	case "ON":

		// -------------------------------------------------------------
		// ШАГ 1: ЯДЕРНЫЙ ПРЕДОХРАНИТЕЛЬ
		// Проверяем, освободил ли настоящий OpenSSH порт 22.
		// Если рокировка не выполнена — порт 22 занят легитимным SSH,
		// и ловушка не может его занять.
		//
		// ОБХОД: Переменная окружения `AMBER_FORCE_TARPIT=TRUE`
		// позволяет обойти проверку (для экстренных случаев).
		// -------------------------------------------------------------
		if sys.DetectActiveSshPort() == fmt.Sprintf("%d", config.C.StandardSshPort) &&
			strings.ToUpper(os.Getenv("AMBER_FORCE_TARPIT")) != "TRUE" {
			sys.LogAction("TARPIT_SERVICE", "PORT_CONGESTION_LOCK", "ALERT",
				"Запуск ловушки заблокирован: легитимный процесс OpenSSH продолжает удерживать порт 22")
			return fmt.Errorf("блокировка запуска: OpenSSH все еще удерживает порт 22")
		}

		// -------------------------------------------------------------
		// ШАГ 2: ВЫТЕСНЕНИЕ БРОНИ
		// Безусловно деактивируем лимитер на порту 22 во избежание
		// коллизии Netfilter. Лимитер и ловушка не могут работать
		// на одном порту одновременно.
		// -------------------------------------------------------------
		_ = SetCustomRateLimit(22, "open_ssh", "Open SSH", "OFF")
		time.Sleep(300 * time.Millisecond) // Фирменная пауза стабилизации таблиц ядра
		sys.LogAction("TARPIT_SERVICE", "NETFILTER_PREPARE", "SUCCESS",
			"Предварительное изменение лимитеров Netfilter и зачистка порта 22 завершены")

		// -------------------------------------------------------------
		// ШАГ 3: ПОДГОТОВКА UFW
		// Выжигаем устаревшие сокеты-активаторы и мусорные правила.
		// Создаём чистое правило `allow 22/tcp` с корпоративным комментарием.
		// -------------------------------------------------------------

		// Выжигаем устаревшие юниты сокетов (наследие старых версий)
		// -------------------------------------------------------------
		// БЛОК 3.1: ЗАЧИСТКА НАСЛЕДИЯ СТАРЫХ ВЕРСИЙ
		// Ошибки больше не игнорируются, но сбой удаления наследия
		// некритичен: он не должен блокировать активацию ловушки.
		// -------------------------------------------------------------

		// Останавливаем старый сокет-активатор ловушки, если он ещё существует.
		stopSocketRes := sys.RunTimeout(10*time.Second, "systemctl", "stop", "ssh_tarpit.socket")

		// Если юнит отсутствует или уже остановлен, команда может вернуть ошибку.
		// Это не критично, но событие обязано быть в журнале.
		// event=systemctl.legacy_socket_stop_failed
		stopSocketRes.LogWarnIfErr("TARPIT_SERVICE", "LEGACY_SOCKET_STOP", "event=systemctl.legacy_socket_stop_failed")

		// Отключаем автозапуск старого сокет-активатора.
		disableSocketRes := sys.RunTimeout(10*time.Second, "systemctl", "disable", "ssh_tarpit.socket")

		// Если юнит отсутствует, ошибка некритична, но должна быть видима.
		// event=systemctl.legacy_socket_disable_failed
		disableSocketRes.LogWarnIfErr("TARPIT_SERVICE", "LEGACY_SOCKET_DISABLE", "event=systemctl.legacy_socket_disable_failed")

		// Удаляем файл старого юнита. Это файловая операция, не внешняя команда.
		// В рамках 3.1 не трогаем файловые операции — их закроет 3.2.
		_ = os.Remove("/etc/systemd/system/ssh_tarpit.socket")

		// -------------------------------------------------------------
		// БЛОК 3.1: ПРЕВЕНТИВНОЕ ВЫЖИГАНИЕ СТАРЫХ ПРАВИЛ ПОРТА 22
		// Эти правила могут отсутствовать, поэтому ошибка удаления
		// считается некритичной, но обязана быть залогирована.
		// -------------------------------------------------------------

		// Список команд очистки порта 22 перед взведением чистого правила ловушки.
		// Порядок важен: сначала лимитер, потом reject, потом allow.
		cleanupCommands := [][]string{
			{"--force", "delete", "limit", "22/tcp"},
			{"--force", "delete", "reject", "22/tcp"},
			{"--force", "delete", "allow", "22/tcp"},
		}

		// Выполняем каждую команду очистки через единый интерфейс.
		for _, args := range cleanupCommands {
			// Выполняем команду с таймаутом 10 секунд.
			// Таймаут защищает протокол от зависшего UFW или блокировки таблиц.
			cleanRes := sys.RunTimeout(10*time.Second, "ufw", args...)

			// Если удаление не подтверждено, пишем WARNING.
			// event=ufw.pre_clean_failed — единый код для очистки порта 22.
			cleanRes.LogWarnIfErr("TARPIT_SERVICE", "UFW_PRE_CLEAN", "event=ufw.pre_clean_failed")
		}

		// -------------------------------------------------------------
		// ВЗВЕДЕНИЕ ЧИСТОГО ПРАВИЛА КАПКАНА
		// Это критичная команда: без неё бот не сможет дойти до ловушки.
		// Поэтому ошибка возвращается наружу и прерывает протокол.
		// -------------------------------------------------------------

		// Комментарий соответствует регламенту маркеров Netfilter:
		// "Amber Guard Lab. Active Tarpit Station".
		commentMsg := "Amber Guard Lab. Active Tarpit Station"

		// Выполняем добавление правила.
		allowRes := sys.RunTimeout(10*time.Second, "ufw", "allow", "22/tcp", "comment", commentMsg)

		// Если правило не добавилось — ловушка будет недоступна извне.
		// Это критический сбой протокола.
		if allowRes.Err != nil {
			// Для диагностики берём stderr внешней команды.
			// Если stderr пуст, error всё равно содержит причину из Go.
			stderrDetails := strings.TrimSpace(allowRes.Stderr)

			// Возвращаем ошибку с контекстом: причина + вывод команды.
			return fmt.Errorf("ошибка инициализации шлюза UFW: %w; stderr=%s", allowRes.Err, stderrDetails)
		}

		// -------------------------------------------------------------
		// ПЕРЕЗАГРУЗКА UFW
		// UFW обычно применяет правило сразу, но протокол исторически
		// делает reload. Ошибка перезагрузки некритична, если правило
		// уже добавлено, но сбой обязан быть в журнале.
		// -------------------------------------------------------------
		reloadRes := sys.RunTimeout(10*time.Second, "ufw", "reload")

		// event=ufw.reload_failed — машинный код сбоя перезагрузки.
		reloadRes.LogWarnIfErr("TARPIT_SERVICE", "UFW_RELOAD", "event=ufw.reload_failed")

		// Проверяем, что правило реально присутствует в выводе UFW.
		// Если статус недоступен, VerifyUfwRulePresence сама залогирует сбой.
		VerifyUfwRulePresence(commentMsg, true)

		// SUCCESS пишем для высокоуровневого шага: правило добавлено,
		// критичная команда `ufw allow` подтверждена.
		sys.LogAction("TARPIT_SERVICE", "UFW_GATE_OPEN", "SUCCESS",
			"Шлюз UFW для Дегтярной Ямы успешно открыт: ufw allow 22/tcp")

		// -------------------------------------------------------------
		// ШАГ 4: ДЕЛЕГИРОВАНИЕ В TARPITCTL
		// Записываем декларацию в инвентарь и убеждаемся, что демон запущен.
		// Демон прочитает инвентарь и поднимет слушатель на порту 22.
		//
		// ВАЖНО: Мы НЕ создаём маркер здесь. Маркер создаёт ДЕМОН
		// после реального поднятия слушателя.
		//
		// НОВОЕ В v8.0.1: Прямые вызовы `systemctl` и запись маркера
		// заменены на вызов `tarpitctl.ActivateCoreTarpit()`.
		// -------------------------------------------------------------
		coreConfig := sys.TarpitConfig{
			SSHVersion:    "SSH-2.0-OpenSSH_9.6p1 Ubuntu-3ubuntu13", // Эталонный камуфляж
			DelayStep:     config.C.DelayStep,
			DelayVariance: config.C.DelayVariance,
			MaxConn:       config.C.TarpitMaxConn,
		}

		if err := tarpitctl.ActivateCoreTarpit(coreConfig); err != nil {
			sys.LogAction("TARPIT_SERVICE", "TARPITCTL_ACTIVATE_FAIL", "ERROR",
				fmt.Sprintf("Сбой активации через tarpitctl: %v", err))
			return fmt.Errorf("критический сбой активации ловушки: %w", err)
		}

		// Сбрасываем кэш UFW для мгновенного обновления сетки TUI
		ResetUfwCacheSnapshot()

		sys.LogAction("TARPIT_SERVICE", "TARPIT_ON_COMPLETE", "SUCCESS",
			"Дегтярная Яма на порту 22 успешно активирована через tarpitctl")
		return nil

	// =================================================================
	// TARPIT OFF: Деактивация Дегтярной Ямы на порту 22
	// =================================================================
	//
	// ПОРЯДОК ОПЕРАЦИЙ:
	//   1. Делегирование в tarpitctl: запись в инвентарь, остановка воркера
	//   2. Выжигание UFW-правил ловушки на порту 22
	//   3. Восстановление периметра порта 22 (на основе рокировки)
	//
	// ВАЖНО: Ловушка деактивируется ДО выжигания UFW.
	// Сначала снимаем слушателя, потом закрываем шлюз.
	// =================================================================
	case "OFF":

		// -------------------------------------------------------------
		// ШАГ 1: ДЕЛЕГИРОВАНИЕ В TARPITCTL
		// Записываем декларацию `state=STOPPED` в инвентарь.
		// Демон прочитает инвентарь и снимет слушатель порта 22.
		// Если это была последняя активная ловушка — демон остановится.
		//
		// ВАЖНО: Мы НЕ удаляем маркер здесь. Маркер удаляет ДЕМОН
		// после реального снятия слушателя.
		//
		// НОВОЕ В v8.0.1: Прямые вызовы `systemctl disable/stop`
		// и удаление маркера заменены на вызов `tarpitctl.DeactivateCoreTarpit()`.
		// -------------------------------------------------------------
		if err := tarpitctl.DeactivateCoreTarpit(); err != nil {
			sys.LogAction("TARPIT_SERVICE", "TARPITCTL_DEACTIVATE_FAIL", "ERROR",
				fmt.Sprintf("Сбой деактивации через tarpitctl: %v", err))
			// Не возвращаем ошибку — продолжаем очистку UFW
		}

		// -------------------------------------------------------------
		// ШАГ 2: ВЫЖИГАНИЕ UFW-ПРАВИЛ ЛОВУШКИ
		// БЛОК 3.1: удаляем все правила, связанные с ловушкой на порту 22.
		// Ошибки удаления больше не игнорируются.
		// -------------------------------------------------------------

		// Флаг подтверждения полного закрытия гейта.
		// Если хотя бы одна команда очистки не подтверждена — шаг считается деградированным.
		gateCloseOK := true

		// Список правил ловушки, которые должны быть удалены.
		trapRuleDeletes := [][]string{
			{"--force", "delete", "allow", "22/tcp"},
			{"--force", "delete", "limit", "22/tcp"},
			{"--force", "delete", "reject", "22/tcp"},
		}

		// Последовательно выжигаем правила ловушки.
		for _, args := range trapRuleDeletes {
			// Выполняем удаление через единый интерфейс.
			delRes := sys.RunTimeout(10*time.Second, "ufw", args...)

			// Если удаление не подтверждено, фиксируем сбой и снижаем флаг успеха.
			if delRes.Err != nil {
				gateCloseOK = false

				// event=ufw.trap_rule_delete_failed — машинный код сбоя удаления правила.
				delRes.LogWarnIfErr("TARPIT_SERVICE", "UFW_TRAP_RULE_DELETE", "event=ufw.trap_rule_delete_failed")
			}
		}

		// Применяем изменения перезагрузкой.
		// Ошибка перезагрузки не всегда означает, что правила не удалены,
		// но состояние применения становится неподтверждённым.
		reloadRes := sys.RunTimeout(10*time.Second, "ufw", "reload")

		// Если перезагрузка не подтверждена, также снижаем флаг успеха.
		if reloadRes.Err != nil {
			gateCloseOK = false

			// event=ufw.reload_failed — машинный код сбоя перезагрузки.
			reloadRes.LogWarnIfErr("TARPIT_SERVICE", "UFW_RELOAD", "event=ufw.reload_failed")
		}

		// Проверяем, что правило ловушки реально исчезло из вывода.
		// Если статус недоступен, VerifyUfwRulePresence сама залогирует сбой.
		VerifyUfwRulePresence("Amber Guard Lab. Active Tarpit Station", false)

		// Пишем итоговое событие шага.
		// Если все команды подтверждены — SUCCESS.
		// Если были сбои — WARNING с машинным кодом деградации.
		if gateCloseOK {
			sys.LogAction("TARPIT_SERVICE", "UFW_GATE_CLOSED", "SUCCESS",
				"Шлюз UFW Дегтярной Ямы закрыт. Правила порта 22 выжжены.")
		} else {
			sys.LogAction("TARPIT_SERVICE", "UFW_GATE_CLOSED", "WARNING",
				"event=ufw.gate_close_degraded port=22. Закрытие гейта ловушки завершено с некритичными сбоями.")
		}

		// -------------------------------------------------------------
		// ШАГ 3: СТЕРИЛИЗАЦИЯ ПЕРИМЕТРА
		// Восстанавливаем периметр порта 22 на основе персистентной
		// геометрии сервера.
		//
		// Если рокировка НЕ выполнена → порт 22 возвращается в режим
		// "SSH Standard" (открыт для легитимного SSH).
		//
		// Если рокировка ВЫПОЛНЕНА → порт 22 остаётся пустым и
		// замурованным (нативный аппаратный "Connection refused").
		// Никаких новых правил для порта 22 не создаётся.
		// -------------------------------------------------------------
		markerCastling := config.MarkerSshMoved
		if _, err := os.Stat(markerCastling); err != nil {
			// Рокировка НЕ выполнена → восстанавливаем стандартный доступ.
			// Это критичный шаг для административного доступа,
			// поэтому сбои обязаны быть видны в журнале.

			// Добавляем стандартное правило доступа на порт 22.
			allowStdRes := sys.RunTimeout(10*time.Second, "ufw", "allow", "22/tcp",
				"comment", "Amber Guard Lab. SSH Standard")

			// Если правило не добавилось, логируем как некритичный сбой,
			// потому что протокол всё ещё продолжает работу.
			// Однако администратор должен увидеть деградацию периметра.
			// event=ufw.standard_allow_failed
			allowStdRes.LogWarnIfErr("TARPIT_SERVICE", "PERIMETER_RESTORE", "event=ufw.standard_allow_failed")

			// Применяем изменения перезагрузкой.
			reloadStdRes := sys.RunTimeout(10*time.Second, "ufw", "reload")

			// Если перезагрузка не подтверждена, это также фиксируется.
			// event=ufw.reload_failed
			reloadStdRes.LogWarnIfErr("TARPIT_SERVICE", "PERIMETER_RELOAD", "event=ufw.reload_failed")

			// Проверяем, что стандартное правило появилось в выводе.
			// Если статус недоступен, VerifyUfwRulePresence сама залогирует сбой.
			VerifyUfwRulePresence("Amber Guard Lab. SSH Standard", true)

			// Если обе критичные команды подтверждения не дали,
			// считаем восстановление периметра деградированным.
			if allowStdRes.Err != nil || reloadStdRes.Err != nil {
				sys.LogAction("TARPIT_SERVICE", "PERIMETER_RESTORE", "WARNING",
					"event=perimeter.restore_degraded port=22. Рокировка не выполнена, но восстановление периметра завершилось с некритичным сбоем.")
			} else {
				sys.LogAction("TARPIT_SERVICE", "PERIMETER_RESTORE", "SUCCESS",
					"Рокировка не выполнена. Периметр порта 22 возвращён в стандартный режим OpenSSH")
			}
		} else {
			// Рокировка ВЫПОЛНЕНА → порт 22 остаётся замурованным
			sys.LogAction("TARPIT_SERVICE", "PERIMETER_MUTING", "SUCCESS",
				"Обнаружена активная рокировка. Периметр порта 22 остается замурованным")
		}

		// Сбрасываем кэш UFW для мгновенного обновления сетки TUI
		ResetUfwCacheSnapshot()

		sys.LogAction("TARPIT_SERVICE", "TARPIT_OFF_COMPLETE", "SUCCESS",
			"Дегтярная Яма на порту 22 успешно деактивирована. Периметр восстановлен.")
		return nil

	// =================================================================
	// TARPIT CHECK: Проверка состояния Дегтярной Ямы
	// =================================================================
	//
	// НОВОЕ В v8.0.1: Вместо опроса `systemctl is-active` напрямую,
	// проверяем через `tarpitctl.IsDaemonAlive()` и наличие маркера.
	// Это обеспечивает консистентность с новой архитектурой.
	// =================================================================
	case "CHECK":
		// 1. Проверяем, жив ли вообще демон
		if !tarpitctl.IsDaemonAlive() {
			return fmt.Errorf("демон ловушки деактивирован")
		}

		// 2. Проверяем, есть ли базовая ловушка (порт 22) в инвентаре и активна ли она
		inv, err := sys.LoadTarpitInventory(sys.TarpitInventoryPath)
		if err != nil {
			return fmt.Errorf("инвентарь недоступен")
		}

		coreTrapID := sys.GenerateTarpitID(config.C.StandardSshPort) // agl_tarpit_listener_port.22
		trap, exists := inv.Traps[coreTrapID]

		if !exists || trap.State != sys.StateRunning {
			return fmt.Errorf("базовая ловушка порта 22 не найдена в инвентаре или остановлена")
		}

		return nil // Всё идеально: демон жив и порт 22 в инвентаре заявлен как RUNNING
	}

	return fmt.Errorf("запрошено неизвестное действие ловушки: %s", action)
}
