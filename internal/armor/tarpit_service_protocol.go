// ВЕРСИЯ: v8.0.1
// РОЛЬ: Тонкий адаптер между TUI/роутером и новым контроллером `tarpitctl`.
//
//	Управляет UFW-правилами порта 22 и делегирует управление ловушкой.
//
// ============================================================================
//
// АРХИТЕКТУРНАЯ ПОЗИЦИЯ:
//
//	Этот файл — АДАПТЕР СОВМЕСТИМОСТИ между старой и новой архитектурой.
//	Он сохраняет интерфейс `SetTarpitProtocol(action)` для совместимости
//	с существующим кодом `armor.ExecuteArmorRoute("TARPIT", ...)`,
//	но делегирует реальное управление ловушкой в `tarpitctl`.
//
// РАЗДЕЛЕНИЕ ОТВЕТСТВЕННОСТИ:
//   - `armor` (ЭТОТ ФАЙЛ): Управление UFW-правилами порта 22
//   - `tarpitctl`: Управление инвентарём, демоном, маркерами
//   - `tarpit` (демон): Исполнение ловушек, создание/удаление маркеров
//
// ПОТОК УПРАВЛЕНИЯ ПРИ TARPIT_ON:
//  1. armor: Деактивирует лимитер на порту 22 (устранение коллизии)
//  2. armor: Выжигает старые UFW-правила на порту 22
//  3. armor: Создаёт правило `ufw allow 22/tcp` с комментарием
//  4. tarpitctl: Записывает декларацию в `tarpit_inventory.json`
//  5. tarpitctl: Убеждается, что демон запущен
//  6. Демон: Читает инвентарь, поднимает слушатель, создаёт маркер
//
// ПОТОК УПРАВЛЕНИЯ ПРИ TARPIT_OFF:
//  1. tarpitctl: Записывает декларацию `state=STOPPED` в инвентарь
//  2. Демон: Читает инвентарь, снимает слушатель, удаляет маркер
//  3. Демон: Если нет других активных ловушек — останавливается
//  4. armor: Выжигает UFW-правила ловушки на порту 22
//  5. armor: Восстанавливает периметр порта 22 (на основе рокировки)
//
// ### [2026-08-22] — Мажорный рефакторинг протокола (v8.0.1)
// - Управление ловушкой делегировано в `internal/tarpitctl`.
// - Убраны прямые вызовы `systemctl start/stop/enable/disable`.
// - Убрана прямая генерация юнита `agld_tarpit.service`.
// - Убрана прямая запись/удаление маркера `agl_tarpit_listener_port.22`.
// - UFW-менеджмент порта 22 сохранён в `armor` (домен брандмауэра).
// - `CHECK` переписан: опрашивает `tarpitctl` вместо `systemctl is-active`.
// - `VerifyUfwRulePresence` сохранена без изменений (утилита).
// ============================================================================
