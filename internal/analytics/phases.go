// ПРИНЦИП:
//   - фаза не выдумывается при отсутствии данных;
//   - каждая фаза имеет уровень опасности и уверенность;
//   - каждый вердикт имеет доказательства и причины;
//   - OUR_CLOSE не приписывается боту без оговорки;
//   - IAT-математика должна быть безопасной.
