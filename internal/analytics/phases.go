package analytics

import (
	"fmt"
)

// Коды фаз угрозы.
//
// Храним как строки, чтобы веб-панель и JSON были читаемыми.
// Коды стабильные, а подписи можно менять отдельно для i18n.
const (
	// PhaseCodeUnknown — фаза не определена.
	//
	// Это честный результат, если:
	//   - недостаточно данных;
	//   - метрики битые;
	//   - условия фаз не выполнены;
	//   - сессия закрыта нашей стороной без полезного поведения.
	PhaseCodeUnknown = "PHASE_UNKNOWN"

	// PhaseCodeBlindRecon — ФАЗА 1: слепой сканирующий штурм.
	//
	// Признаки:
	//   - нет чтений;
	//   - бот только трогает порт;
	//   - полезная нагрузка не передаётся.
	PhaseCodeBlindRecon = "PHASE_1_BLIND_RECON_L4"

	// PhaseCodeBannerRecon — ФАЗА 2: активный сбор баннеров.
	//
	// Признаки:
	//   - есть короткие или средние чтения;
	//   - нет больших чтений;
	//   - закрытие по FIN или TIMEOUT.
	PhaseCodeBannerRecon = "PHASE_2_BANNER_RECON_L7"

	// PhaseCodePayloadProbe — ФАЗА 3: зондирование полезной нагрузкой.
	//
	// Признаки:
	//   - есть большие чтения;
	//   - бот пытается передать или продавить данные;
	//   - полное подтверждение требует CloseReason == TIMEOUT.
	PhaseCodePayloadProbe = "PHASE_3_PAYLOAD_PROBE"
)

// Уровни опасности фазы.
//
// Храним как строки для понятного отображения в интерфейсе.
const (
	// DangerLevelUnknown — опасность не определена.
	//
	// Используется, когда данных недостаточно.
	// Это не "безопасно", а "неизвестно".
	DangerLevelUnknown = "UNKNOWN"

	// DangerLevelLow — низкая опасность.
	//
	// Обычно соответствует слепому сканированию без полезной нагрузки.
	DangerLevelLow = "LOW"

	// DangerLevelMedium — средняя опасность.
	//
	// Обычно соответствует сбору баннеров и коротким запросам.
	DangerLevelMedium = "MEDIUM"

	// DangerLevelHigh — высокая опасность.
	//
	// Обычно соответствует попыткам передачи крупной полезной нагрузки.
	DangerLevelHigh = "HIGH"
)

// Профили инструмента бота по ритму IAT.
//
// Это поведенческая гипотеза о том, что управляет сканером.
const (
	// ToolProfileUnknown — тип инструмента не определён.
	//
	// Используется, если ритм не даёт явного сигнала.
	ToolProfileUnknown = "UNKNOWN"

	// ToolProfileTimerBot — жёсткий автоматизированный скрипт.
	//
	// Признаки:
	//   - паузы одинаковые;
	//   - дисперсия нулевая;
	//   - таймер бота работает механически.
	ToolProfileTimerBot = "TIMER_BOT"

	// ToolProfileHumanEmulation — эмуляция человека или рваный канал.
	//
	// Признаки:
	//   - высокая дисперсия пауз;
	//   - большие разрывы между минимальным и максимальным IAT;
	//   - возможна попытка имитировать человека;
	//   - также возможен плохой прокси-канал.
	ToolProfileHumanEmulation = "HUMAN_EMULATION_OR_BAD_PROXY"
)

// IATHighDispersionThreshold задаёт порог высокой дисперсии ритма.
//
// Значение взято из исходного алгоритма:
//   - если дисперсионный след больше 50000, ритм считается рваным.
//
// Важно:
//   - мы считаем дисперсионный след по формуле из ТЗ;
//   - это не классическая статистическая дисперсия, а оценочный маркер;
//   - позже порог можно вынести в конфигурацию.
const IATHighDispersionThreshold = 50000.0

// PhaseConfidenceMax задаёт максимальную уверенность фазы.
//
// Почему не 100:
//   - фаза является поведенческой гипотезой;
//   - даже яркие признаки могут быть искажены капканом или сетью;
//   - 90% оставляем как практический потолок.
const PhaseConfidenceMax = 90

// PhaseResult описывает результат фазовой классификации одной сессии.
//
// Это не просто строка "ФАЗА 2".
// Это полноценный вердикт:
//   - код фазы;
//   - человекочитаемая подпись;
//   - уровень опасности;
//   - уверенность;
//   - профиль инструмента;
//   - доказательства;
//   - причины.
type PhaseResult struct {
	// Code — стабильный машинный код фазы.
	//
	// Используется для:
	//   - API;
	//   - внутренней логики;
	//   - графиков;
	//   - фильтров.
	Code string `json:"code"`

	// Label — человекочитаемая подпись фазы.
	//
	// Используется для веб-панели.
	// Позже может быть заменён на i18n-строку.
	Label string `json:"label"`

	// DangerLevel — уровень опасности фазы.
	//
	// Может быть:
	//   - UNKNOWN;
	//   - LOW;
	//   - MEDIUM;
	//   - HIGH.
	DangerLevel string `json:"danger_level"`

	// Confidence — уверенность фазовой классификации.
	//
	// Это не Match_Score и не уверенность профиля.
	// Это уверенность именно в текущей поведенческой фазе.
	Confidence int `json:"confidence"`

	// ToolProfile — гипотеза о типе инструмента бота.
	//
	// Может быть:
	//   - UNKNOWN;
	//   - TIMER_BOT;
	//   - HUMAN_EMULATION_OR_BAD_PROXY.
	ToolProfile string `json:"tool_profile"`

	// CloseReason — нормализованная причина закрытия сессии.
	//
	// Сохраняем её в результат, чтобы веб-панель могла показать
	// связь между фазой и способом закрытия.
	CloseReason string `json:"close_reason"`

	// IATCount — количество интервалов между успешными чтениями.
	//
	// Если поле было невалидно, остаётся ноль.
	// Это нужно интерпретировать вместе с причинами.
	IATCount uint64 `json:"iat_count"`

	// IATSumMs — сумма интервалов в миллисекундах.
	//
	// Если поле было невалидно, остаётся ноль.
	// Это нужно интерпретировать вместе с причинами.
	IATSumMs uint64 `json:"iat_sum_ms"`

	// IATMinMs — минимальный интервал в миллисекундах.
	//
	// Если поле было невалидно, остаётся ноль.
	// Это нужно интерпретировать вместе с причинами.
	IATMinMs uint64 `json:"iat_min_ms"`

	// IATMaxMs — максимальный интервал в миллисекундах.
	//
	// Если поле было невалидно, остаётся ноль.
	// Это нужно интерпретировать вместе с причинами.
	IATMaxMs uint64 `json:"iat_max_ms"`

	// IATDispersion — дисперсионный след ритма.
	//
	// Это оценочный маркер по формуле из ТЗ:
	//   SumSq - (Sum * Sum / Count)
	//
	// Если Count == 0, значение равно 0.
	// Если формула даёт отрицательный след из-за округления,
	// он принудительно обнуляется.
	IATDispersion float64 `json:"iat_dispersion"`

	// ReadTiny — чтения 0–64 байта.
	//
	// Маркер коротких зондов и баннерных проверок.
	ReadTiny uint64 `json:"read_tiny"`

	// ReadSmall — чтения 65–256 байт.
	//
	// Маркер логинов, команд и коротких запросов.
	ReadSmall uint64 `json:"read_small"`

	// ReadMedium — чтения 257–1024 байт.
	//
	// Маркер более осмысленного обмена данными.
	ReadMedium uint64 `json:"read_medium"`

	// ReadLarge — чтения свыше 1024 байт.
	//
	// Маркер попыток передачи крупной полезной нагрузки.
	ReadLarge uint64 `json:"read_large"`

	// Evidence — список доказательств.
	//
	// Здесь фиксируем:
	//   - какие чтения сработали;
	//   - какой CloseReason подтвердил фазу;
	//   - какой ритм IAT найден.
	//
	// Это нужно для объяснимости в веб-панели.
	Evidence []string `json:"evidence"`

	// Reasons — список причин и оговорок.
	//
	// Здесь фиксируем:
	//   - почему фаза не определена;
	//   - какие метрики отсутствуют;
	//   - почему уверенность снижена;
	//   - есть ли вмешательство нашей стороны.
	Reasons []string `json:"reasons"`
}

// ClassifyPhase выполняет фазовую классификацию одного события.
//
// Аргументы:
//   - rec: нормализованное событие.
//
// Возврат:
//   - PhaseResult с полным вердиктом.
//
// Поведение:
//   - если данных недостаточно, возвращаем UNKNOWN;
//   - если условия фаз выполняются, возвращаем фазу;
//   - если есть подозрение без полного подтверждения, помечаем это;
//   - всегда добавляем доказательства и причины.
//
// Важно:
//   - функция не меняет событие;
//   - функция не меняет профили;
//   - функция не строит прогнозы;
//   - она только классифицирует одну сессию.
func ClassifyPhase(rec EventRecord) PhaseResult {
	// Создаём базовый результат.
	//
	// По умолчанию фаза неизвестна.
	// Это честное состояние, пока данные не подтвердят обратное.
	result := PhaseResult{
		Code:        PhaseCodeUnknown,
		Label:       "ФАЗА НЕ ОПРЕДЕЛЕНА",
		DangerLevel: DangerLevelUnknown,
		Confidence:  20,
		ToolProfile: ToolProfileUnknown,
		CloseReason: rec.CloseReason,
		Evidence:    []string{},
		Reasons:     []string{},
	}

	// Переносим в результат IAT-метрики, если они валидны.
	//
	// Это нужно для веб-панели и отладки.
	// Если метрика невалидна, оставляем ноль и позже пишем причину.
	if rec.IATCountValid {
		result.IATCount = rec.IATCount
	}
	if rec.IATSumMsValid {
		result.IATSumMs = rec.IATSumMs
	}
	if rec.IATMinMsValid {
		result.IATMinMs = rec.IATMinMs
	}
	if rec.IATMaxMsValid {
		result.IATMaxMs = rec.IATMaxMs
	}

	// Переносим в результат метрики чтений, если они валидны.
	//
	// Это нужно для веб-панели и отладки.
	// Если метрика невалидна, оставляем ноль и позже пишем причину.
	if rec.ReadTinyValid {
		result.ReadTiny = rec.ReadTiny
	}
	if rec.ReadSmallValid {
		result.ReadSmall = rec.ReadSmall
	}
	if rec.ReadMediumValid {
		result.ReadMedium = rec.ReadMedium
	}
	if rec.ReadLargeValid {
		result.ReadLarge = rec.ReadLarge
	}

	// Проверяем, что все метрики чтений валидны.
	//
	// Фазовая классификация опирается на чтения.
	// Если чтения битые, фаза не может быть достоверной.
	//
	// Это осознанная строгость:
	// лучше вернуть UNKNOWN, чем выдумать фазу.
	readsValid := rec.ReadTinyValid &&
		rec.ReadSmallValid &&
		rec.ReadMediumValid &&
		rec.ReadLargeValid

	// Если чтения невалидны, фиксируем причину и возвращаем неизвестную фазу.
	//
	// Это защищает от ложной интерпретации повреждённых данных.
	// Администратор должен видеть, что проблема в качестве данных.
	if !readsValid {
		result.Reasons = appendUnique(
			result.Reasons,
			"метрики чтений невалидны; фазовая классификация невозможна",
		)
		return result
	}

	// Если причина закрытия невалидна, фиксируем оговорку.
	//
	// Мы не всегда полностью останавливаем классификацию,
	// потому что чтения могут быть полезны.
	//
	// Но если причина закрытия битая, уверенность должна быть ниже.
	//
	// Это честный подход:
	//   - данные есть;
	//   - но интерпретация закрытия невозможна.
	if !rec.CloseReasonValid {
		result.Confidence -= 10
		result.Reasons = appendUnique(
			result.Reasons,
			"причина закрытия невалидна или не распознана",
		)
	}

	// Если сессия закрыта нашей стороной, обязательно фиксируем это.
	//
	// Почему это важно:
	//   - OUR_CLOSE не является поведением бота;
	//   - это действие комплекса;
	//   - нельзя приписывать боту то, что сделал капкан.
	//
	// Мы не отбрасываем сессию, но снижаем уверенность.
	// Это сохраняет честность поведенческого анализа.
	if rec.CloseReason == "OUR_CLOSE" {
		result.Confidence -= 15
		result.Reasons = appendUnique(
			result.Reasons,
			"сессия закрыта комплексом; поведение бота интерпретируется с оговоркой",
		)
	}

	// Вычисляем признак ФАЗЫ 1.
	//
	// ФАЗА 1 означает:
	//   - бот коснулся ловушки;
	//   - но не прочитал никаких данных;
	//   - полезная нагрузка не наблюдалась.
	//
	// Это типичный слепой сканер или первичный зонд.
	allReadsZero := rec.ReadTiny == 0 &&
		rec.ReadSmall == 0 &&
		rec.ReadMedium == 0 &&
		rec.ReadLarge == 0

	// Вычисляем признак ФАЗЫ 2.
	//
	// ФАЗА 2 означает:
	//   - есть короткие или средние чтения;
	//   - нет крупных чтений;
	//   - сессия закрыта по FIN или TIMEOUT.
	//
	// Это активный сбор баннеров или коротких ответов.
	//
	// Почему только FIN или TIMEOUT:
	//   - FIN может означать внутренний таймаут бота;
	//   - TIMEOUT может означать, что бот висел в капкане;
	//   - RST в этой фазе может быть признаком паники,
	//     но исходный алгоритм не включает его в чистую ФАЗУ 2.
	isPhase2 := (rec.ReadSmall > 0 || rec.ReadMedium > 0) &&
		rec.ReadLarge == 0 &&
		(rec.CloseReason == "FIN" || rec.CloseReason == "TIMEOUT")

	// Вычисляем признак ФАЗЫ 3.
	//
	// ФАЗА 3 означает:
	//   - есть крупные чтения;
	//   - сессия удержана до TIMEOUT;
	//   - бот пытался работать с крупной полезной нагрузкой.
	//
	// Это самый серьёзный поведенческий маркер.
	//
	// Почему требуется TIMEOUT:
	//   - TIMEOUT показывает, что сессия реально висела в капкане;
	//   - это усиливает уверенность, что бот был вовлечён;
	//   - без TIMEOUT крупный чтение может быть короче и менее показателен.
	isPhase3 := rec.ReadLarge > 0 &&
		rec.CloseReason == "TIMEOUT"

	isPhase3Suspect := rec.ReadLarge > 0 &&
		rec.CloseReason != "TIMEOUT"

	switch {
	case allReadsZero:
		// ФАЗА 1: слепой сканирующий штурм.
		//
		// Бот не оставил следов чтения.
		// Это значит, что он, скорее всего, только проверял порт.
		//
		// Уровень опасности низкий, потому что:
		//   - нет передачи данных;
		//   - нет полезной нагрузки;
		//   - нет признаков эксплуатации.
		result.Code = PhaseCodeBlindRecon
		result.Label = "ФАЗА 1: СЛЕПОЙ СКАНИРУЮЩИЙ ШТУРМ (Recon_L4)"
		result.DangerLevel = DangerLevelLow
		result.Confidence = 70

		// Добавляем доказательство.
		//
		// Администратор должен видеть, почему выставлена фаза.
		result.Evidence = appendUnique(
			result.Evidence,
			"все метрики чтений равны нулю",
		)

		// Если сессия закрыта по TIMEOUT, это усиливает фазу.
		//
		// Бот просто висел в капкане, не пытаясь читать.
		// Это классический исполнительный зонд.
		//
		// Немного повышаем уверенность.
		if rec.CloseReason == "TIMEOUT" {
			result.Confidence += 5
			result.Evidence = appendUnique(
				result.Evidence,
				"слепой зонд удержан до TIMEOUT",
			)
		}

		// Если сессия закрыта по RST, фиксируем оговорку.
		//
		// Это может означать:
		//   - панику бота;
		//   - сетевой сброс;
		//   - принудительный обрыв;
		//   - проблему канала.
		//
		// Фазу не меняем, но объясняем особенность.
		if rec.CloseReason == "RST" {
			result.Reasons = appendUnique(
				result.Reasons,
				"слепой зонд закрыт через RST; возможен панический обрыв",
			)
		}

		// Если сессия закрыта по FIN, фиксируем оговорку.
		//
		// Для слепого зонда FIN означает более аккуратное поведение.
		// Это не обязательно повышает опасность, но полезно для досье.
		if rec.CloseReason == "FIN" {
			result.Reasons = appendUnique(
				result.Reasons,
				"слепой зонд закрыт через FIN; возможно аккуратное закрытие",
			)
		}

		// Если сессия закрыта комплексом, причина уже учтена выше.
		// Дополнительных действий не требуется.

	// Если сессия подходит под ФАЗУ 2, применяем её.
	//
	// Это активный сбор баннеров или коротких данных.
	// Бот уже не просто трогает порт, а пытается получить ответ.
	//
	// Уровень опасности средний, потому что:
	//   - есть взаимодействие с приложением;
	//   - есть короткие данные;
	//   - пока нет крупной полезной нагрузки.
	case isPhase2:
		// ФАЗА 2: активный сбор баннеров.
		//
		// Бот читает короткие или средние объёмы.
		// Это может быть:
		//   - сбор баннеров;
		//   - проверка сервиса;
		//   - отправка логинов или команд;
		//   - подготовка к брутфорсу.
		result.Code = PhaseCodeBannerRecon
		result.Label = "ФАЗА 2: АКТИВНЫЙ СБОР БАННЕРОВ (Recon_L7)"
		result.DangerLevel = DangerLevelMedium
		result.Confidence = 75

		// Добавляем базовое доказательство.
		//
		// Администратор должен видеть, что фаза подтверждена чтениями.
		result.Evidence = appendUnique(
			result.Evidence,
			"обнаружены короткие или средние чтения без крупной полезной нагрузки",
		)

		// Если есть средние чтения, это сильнее, чем только короткие.
		//
		// Средние чтения могут означать более осмысленный обмен.
		// Поэтому немного повышаем уверенность.
		if rec.ReadMedium > 0 {
			result.Confidence += 3
			result.Evidence = appendUnique(
				result.Evidence,
				fmt.Sprintf(
					"ReadMedium=%d: обмен данными среднего размера",
					rec.ReadMedium,
				),
			)
		}

		// Если есть короткие чтения, это дополняет картину.
		//
		// Короткие чтения часто означают баннеры, пинги или команды.
		// Добавляем доказательство, но не повышаем уверенность сильно.
		if rec.ReadTiny > 0 {
			result.Evidence = appendUnique(
				result.Evidence,
				fmt.Sprintf(
					"ReadTiny=%d: короткие зонды или баннерные проверки",
					rec.ReadTiny,
				),
			)
		}

		// Если закрытие по FIN, это может означать внутренний таймаут бота.
		//
		// Такой бот:
		//   - имеет лимит ожидания;
		//   - контролирует сессию;
		//   - может адаптироваться к капкану.
		//
		// Это делает фазу более выразительной.
		// Немного повышаем уверенность.
		if rec.CloseReason == "FIN" {
			result.Confidence += 3
			result.Evidence = appendUnique(
				result.Evidence,
				"закрытие по FIN: бот контролирует лимит ожидания",
			)
		}

		// Если закрытие по TIMEOUT, бот висел в капкане.
		//
		// Это тоже полезно, но менее явно говорит о внутреннем таймауте.
		// Добавляем доказательство без сильного повышения уверенности.
		if rec.CloseReason == "TIMEOUT" {
			result.Evidence = appendUnique(
				result.Evidence,
				"закрытие по TIMEOUT: бот оставался в капкане",
			)
		}

	// Если сессия полностью подходит под ФАЗУ 3, применяем её.
	//
	// Это самая серьёзная фаза.
	// Бот работает с крупной полезной нагрузкой и удержан до TIMEOUT.
	//
	// Уровень опасности высокий, потому что:
	//   - есть крупная передача;
	//   - возможна эксплуатация;
	//   - возможна попытка деплоя кода;
	//   - возможен брутфорс или инъекция.
	//
	// Уверенность высокая, потому что:
	//   - крупное чтение подтверждено;
	//   - удержание до TIMEOUT подтверждено.
	case isPhase3:
		// ФАЗА 3: зондирование полезной нагрузкой.
		//
		// Бот пытался передать или обработать крупные данные.
		// Это может быть:
		//   - попытка эксплуатации;
		//   - деплой вредоносного кода;
		//   - брутфорс с крупными ответами;
		//   - внедрение команд.
		result.Code = PhaseCodePayloadProbe
		result.Label = "ФАЗА 3: ЗОНДИРОВАНИЕ PAYLOAD (Попытка брутфорса / внедрения)"
		result.DangerLevel = DangerLevelHigh
		result.Confidence = 80

		// Добавляем основное доказательство.
		//
		// Администратор должен видеть, что фаза подтверждена
		// крупной полезной нагрузкой и удержанием.
		result.Evidence = appendUnique(
			result.Evidence,
			fmt.Sprintf(
				"ReadLarge=%d при CloseReason=TIMEOUT",
				rec.ReadLarge,
			),
		)

		// Если есть средние чтения, добавляем их как контекст.
		//
		// Это показывает, что бот не ограничился одним крупным блоком.
		// Такой обмен может быть более осмысленным.
		if rec.ReadMedium > 0 {
			result.Evidence = appendUnique(
				result.Evidence,
				fmt.Sprintf(
					"ReadMedium=%d: дополнительная полезная нагрузка",
					rec.ReadMedium,
				),
			)
		}

		// Если есть короткие чтения, добавляем их как контекст.
		//
		// Это может означать, что бот сначала проверял баннер,
		// а затем перешёл к полезной нагрузке.
		//
		// Это полезный поведенческий след.
		if rec.ReadTiny > 0 {
			result.Evidence = appendUnique(
				result.Evidence,
				fmt.Sprintf(
					"ReadTiny=%d: предварительные короткие зонды",
					rec.ReadTiny,
				),
			)
		}

	case isPhase3Suspect:
		// ФАЗА 3 (подозрение): крупная нагрузка, но без полного подтверждения.
		result.Code = PhaseCodePayloadProbe
		result.Label = "ФАЗА 3 (ПОДОЗРЕНИЕ): крупная нагрузка без полного подтверждения"
		result.DangerLevel = DangerLevelHigh
		result.Confidence = 55

		result.Evidence = appendUnique(
			result.Evidence,
			fmt.Sprintf("ReadLarge=%d, но CloseReason=%s", rec.ReadLarge, rec.CloseReason),
		)

		result.Reasons = appendUnique(
			result.Reasons,
			"крупная полезная нагрузка обнаружена, но сессия не удержана до TIMEOUT",
		)
	}

	// Ограничиваем уверенность максимумом.
	if result.Confidence > PhaseConfidenceMax {
		result.Confidence = PhaseConfidenceMax
	}

	// Защита от отрицательной уверенности.
	if result.Confidence < 0 {
		result.Confidence = 0
	}

	return result
}

// calculateIATDispersion вычисляет дисперсионный след ритма IAT.
//
// Формула из ТЗ:
//
//	Dispersion = IATSumSqMs - (IATSumMs * IATSumMs / IATCount)
//
// Защита от деления на ноль и переполнения.
func calculateIATDispersion(rec EventRecord) float64 {
	// Если счётчик интервалов нулевой или невалидный, дисперсия невозможна.
	if !rec.IATCountValid || rec.IATCount == 0 {
		return 0
	}

	// Если сумма интервалов невалидна, дисперсия невозможна.
	if !rec.IATSumMsValid {
		return 0
	}

	// Если сумма квадратов невалидна, дисперсия невозможна.
	if !rec.IATSumSqMsValid {
		return 0
	}

	// Вычисляем дисперсионный след.
	//
	// Используем float64 для избежания переполнения при умножении.
	sumSq := float64(rec.IATSumSqMs)
	sum := float64(rec.IATSumMs)
	count := float64(rec.IATCount)

	dispersion := sumSq - (sum*sum)/count

	// Если дисперсия отрицательная из-за округления, обнуляем.
	if dispersion < 0 {
		return 0
	}

	return dispersion
}

// analyzeToolProfile определяет профиль инструмента бота по ритму IAT.
func analyzeToolProfile(rec EventRecord, dispersion float64) string {
	// Если счётчик интервалов нулевой, ритм не анализируется.
	if !rec.IATCountValid || rec.IATCount == 0 {
		return ToolProfileUnknown
	}

	// Если сумма интервалов нулевая, ритм не анализируется.
	if !rec.IATSumMsValid || rec.IATSumMs == 0 {
		return ToolProfileUnknown
	}

	// Если минимальный и максимальный интервалы равны, это жёсткий таймер.
	if rec.IATMinMsValid && rec.IATMaxMsValid &&
		rec.IATMinMs == rec.IATMaxMs && rec.IATMinMs > 0 {
		return ToolProfileTimerBot
	}

	// Если дисперсия нулевая, это тоже жёсткий таймер.
	if dispersion == 0 {
		return ToolProfileTimerBot
	}

	// Если дисперсия высокая, это эмуляция человека или рваный канал.
	if dispersion > IATHighDispersionThreshold {
		return ToolProfileHumanEmulation
	}

	return ToolProfileUnknown
}
