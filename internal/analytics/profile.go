package analytics

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"sort"
	"sync"
	"time"
)

// ProfileIDPrefix задаёт префикс идентификатора профиля.
//
// Зачем:
//   - визуально видно, что это профиль AGL;
//   - удобно искать в логах и веб-панели;
//   - не путается с сырыми IP или токенами.
const ProfileIDPrefix = "AGL_PROFILE_"

// DefaultProfileTTL задаёт срок жизни профиля по умолчанию.
//
// Почему 7 дней:
//   - профиль должен переживать кратковременные паузы бота;
//   - профиль не должен жить вечно без новых подтверждений;
//   - неделя является разумным балансом между памятью и актуальностью.
//
// Позже TTL можно будет вынести в конфигурацию.
const DefaultProfileTTL = 7 * 24 * time.Hour

// Состояния профиля.
//
// Храним как строки, чтобы веб-панель и JSON были читаемыми.
const (
	// ProfileStateActive — профиль активен и имеет достаточную уверенность.
	ProfileStateActive = "ACTIVE"

	// ProfileStateLowConfidence — профиль существует, но уверенность низкая.
	//
	// Такой профиль показывается, но не должен использоваться для жёстких выводов.
	ProfileStateLowConfidence = "LOW_CONFIDENCE"

	// ProfileStateExpired — профиль просрочен.
	//
	// Он может оставаться в памяти для истории,
	// но новые события не должны автоматически опираться на него.
	ProfileStateExpired = "EXPIRED"

	// ProfileStateMerged — профиль был объединён с другим профилем.
	//
	// Это состояние нужно для будущего механизма слияния кластеров.
	ProfileStateMerged = "MERGED"

	// ProfileStateSplit — профиль был разделён.
	//
	// Это состояние нужно для будущего механизма разделения ложных кластеров.
	ProfileStateSplit = "SPLIT"
)

// Границы уверенности профиля.
//
// Почему не 100:
//   - форензика не должна выдавать гипотезу за абсолют;
//   - даже очень сильное совпадение может оказаться совпадением;
//   - 95% оставляем как практический потолок уверенности.
const (
	// ProfileConfidenceMin — минимальная уверенность.
	ProfileConfidenceMin = 0

	// ProfileConfidenceMax — максимальная уверенность.
	ProfileConfidenceMax = 95
)

// Низкий порог уверенности.
//
// Если уверенность падает ниже этого порога,
// профиль переводится в состояние низкой уверенности.
const ProfileLowConfidenceThreshold = 30

// ActorProfile описывает кластерную карточку актора.
//
// Это не один IP и не одна сессия.
// Это накопительная гипотеза о том, что несколько событий,
// несколько IP или несколько поведенческих следов принадлежат
// одному сканеру, боту, скрипту или ботнет-профилю.
type ActorProfile struct {
	// ID — уникальный идентификатор профиля.
	//
	// Генерируется из:
	//   - сетевого отпечатка;
	//   - первого IP;
	//   - времени первого события.
	//
	// После создания профиля ID не меняется.
	// Даже если профиль позже свяжет другие IP.
	ID string `json:"id"`

	// Stack — жёсткий сетевой отпечаток профиля.
	//
	// Это основа первичной идентификации:
	//   - MSS;
	//   - RcvSpace;
	//   - SndWscale;
	//   - RcvWscale.
	Stack StackFingerprint `json:"stack"`

	// StackValid показывает, что профиль имеет полный сетевой отпечаток.
	//
	// Если отпечаток неполный, профиль не должен использоваться
	// для серьёзной связки событий.
	StackValid bool `json:"stack_valid"`

	// State — текущее состояние профиля.
	//
	// Может быть:
	//   - ACTIVE;
	//   - LOW_CONFIDENCE;
	//   - EXPIRED;
	//   - MERGED;
	//   - SPLIT.
	State string `json:"state"`

	// CreatedAt — время создания профиля.
	//
	// Обычно равно времени первого события, которое создало профиль.
	CreatedAt time.Time `json:"created_at"`

	// UpdatedAt — время последнего обновления профиля.
	//
	// Обновляется при:
	//   - новых событиях;
	//   - новых совпадениях;
	//   - изменении уверенности.
	UpdatedAt time.Time `json:"updated_at"`

	// LastSeen — время последней подтверждённой активности профиля.
	//
	// Важно:
	//   - это не обязательно время создания;
	//   - это именно последняя наблюдаемая активность;
	//   - используется для TTL.
	LastSeen time.Time `json:"last_seen"`

	// ExpiresAt — время, после которого профиль считается просроченным.
	//
	// Рассчитывается как:
	//   LastSeen + TTL.
	//
	// Если новых событий нет, профиль деградирует.
	ExpiresAt time.Time `json:"expires_at"`

	// FirstEventTime — самое раннее валидное время события профиля.
	//
	// Используется для хронологии жизни актора.
	FirstEventTime time.Time `json:"first_event_time"`

	// LastEventTime — самое позднее валидное время события профиля.
	//
	// Используется для хронологии жизни актора.
	LastEventTime time.Time `json:"last_event_time"`

	// EventCount — сколько событий связано с профилем.
	//
	// Сюда входят:
	//   - валидные события;
	//   - невалидные события;
	//   - события с проблемами качества данных.
	EventCount int `json:"event_count"`

	// ValidEventCount — сколько валидных событий связано с профилем.
	ValidEventCount int `json:"valid_event_count"`

	// InvalidEventCount — сколько невалидных событий связано с профилем.
	//
	// Это маркер качества данных профиля.
	// Если битых событий много, доверие к профилю должно снижаться.
	InvalidEventCount int `json:"invalid_event_count"`

	// IPCounts — счётчик наблюдений по каждому IP.
	//
	// Это фактические события, где наблюдался IP.
	//
	// Скрываем из JSON напрямую, чтобы не раздувать ответ.
	// Для веб-панели будем отдавать топ через TopIPs().
	IPCounts map[string]int `json:"-"`

	// CountryCounts — счётчик наблюдений по каждой стране.
	//
	// Используется для:
	//   - количества уникальных стран;
	//   - построения топ стран;
	//   - оценки географической ротации.
	//
	// Скрываем из JSON напрямую, чтобы не раздувать ответ.
	CountryCounts map[string]int `json:"-"`

	// BehaviorCounts — счётчик поведенческих маркеров.
	//
	// Например:
	//   - AGGRESSIVE;
	//   - PASSIVE;
	//   - UNKNOWN.
	BehaviorCounts map[string]int `json:"-"`

	// CloseReasonCounts — счётчик причин закрытия.
	//
	// Например:
	//   - FIN;
	//   - RST;
	//   - TIMEOUT;
	//   - OUR_CLOSE;
	//   - UNKNOWN.
	CloseReasonCounts map[string]int `json:"-"`

	// LinkedIPCounts — счётчик связанных IP по матчам.
	//
	// Это не обязательно события, которые уже пришли в профиль.
	// Это могут быть архивные совпадения, найденные через identity.
	//
	// Нужно для:
	//   - отображения связанных адресов;
	//   - оценки ротации;
	//   - будущего слияния профилей.
	LinkedIPCounts map[string]int `json:"-"`

	// RTTCount — сколько событий профиля имели валидный RTT.
	RTTCount uint64 `json:"rtt_count"`

	// RTTMinMs — минимальный RTT в профиле.
	//
	// Значение имеет смысл только при RTTCount > 0.
	RTTMinMs uint32 `json:"rtt_min_ms"`

	// RTTMaxMs — максимальный RTT в профиле.
	//
	// Значение имеет смысл только при RTTCount > 0.
	RTTMaxMs uint32 `json:"rtt_max_ms"`

	// RTTSumMs — сумма RTT для расчёта среднего.
	//
	// Используем uint64, чтобы снизить риск переполнения.
	RTTSumMs uint64 `json:"rtt_sum_ms"`

	// PlannedHoldSumSec — суммарный план удержания по событиям профиля.
	//
	// Считаем только события с валидной парой план/факт.
	PlannedHoldSumSec uint64 `json:"planned_hold_sum_sec"`

	// ActualHoldSumSec — суммарный факт удержания по событиям профиля.
	//
	// Считаем только события с валидной парой план/факт.
	ActualHoldSumSec uint64 `json:"actual_hold_sum_sec"`

	// HoldCount — сколько событий участвуют в суммах план/факт.
	//
	// Если значение равно 0, суммы использовать нельзя.
	HoldCount uint64 `json:"hold_count"`

	// --- АЛГОРИТМ 2: КРИМИНАЛИСТИКА ТОКЕНА В ПРОФИЛЕ ---
	// TokenDriftMs — последний зафиксированный временной дрейф профиля.
	TokenDriftMs int64 `json:"token_drift_ms"`

	// TokenDriftValid показывает, что дрейф был успешно извлечен.
	TokenDriftValid bool `json:"token_drift_valid"`

	// TokenClientPort — последний зафиксированный порт из токена.
	TokenClientPort uint16 `json:"token_client_port"`

	// --- АЛГОРИТМ 3: КЛАССИФИКАТОР ФАЗ УГРОЗЫ ---
	// CurrentPhase — текущая фаза активности актора (например, "ФАЗА 2: АКТИВНЫЙ СБОР БАННЕРОВ").
	CurrentPhase string `json:"current_phase"`

	// ThreatLevel — уровень опасности (LOW, MEDIUM, HIGH).
	ThreatLevel string `json:"threat_level"`

	// --- АЛГОРИТМ 4: ПРОГНОСТИЧЕСКАЯ МОДЕЛЬ ---
	// PredictedVector — прогнозируемый вектор следующей атаки.
	PredictedVector string `json:"predicted_vector"`

	// PredictedProbability — вероятность и горизонт прогноза.
	PredictedProbability string `json:"predicted_probability"`

	// lastPayloadSize — размер полезной нагрузки (ReadLarge + ReadMedium) предыдущей сессии.
	lastPayloadSize uint64 `json:"-"`

	// lastCloseReason — причина закрытия предыдущей сессии.
	lastCloseReason string `json:"-"`

	// lastSessionTime — время предыдущей сессии для расчета интервала атак.
	lastSessionTime time.Time `json:"-"`

	// Confidence — фактическая уверенность профиля.
	//
	// Это не формальный Match_Score.
	// Это накопительная оценка системы.
	//
	// На неё влияют:
	//   - редкость стека;
	//   - совпадения через identity;
	//   - противоречивые события;
	//   - проблемы качества данных.
	Confidence int `json:"confidence"`

	// FalsePositiveRisk — текущий риск ложной склейки.
	//
	// Может быть:
	//   - none;
	//   - low;
	//   - medium;
	//   - high.
	FalsePositiveRisk string `json:"false_positive_risk"`

	// Evidence — список доказательств.
	//
	// Здесь фиксируем:
	//   - совпадение стека;
	//   - дельту RTT;
	//   - распространённые профили;
	//   - важные поведенческие маркеры.
	//
	// Это нужно для объяснимости в веб-панели.
	Evidence []string `json:"evidence"`

	// Reasons — список причин и пояснений.
	//
	// Здесь фиксируем:
	//   - почему уверенность повышена;
	//   - почему уверенность понижена;
	//   - какие данные отсутствуют;
	//   - какие есть противоречия.
	Reasons []string `json:"reasons"`

	// TTL — срок жизни профиля без новой активности.
	//
	// Если профиль не видит новых событий дольше TTL,
	// он должен быть помечен как просроченный.
	TTL time.Duration `json:"ttl"`
}

// ProfileIDFromFingerprint генерирует устойчивый идентификатор профиля.
//
// Аргументы:
//   - fp: сетевой отпечаток;
//   - seedIP: первый или опорный IP профиля;
//   - seedTime: время опорного события.
//
// Возврат:
//   - строковый идентификатор профиля.
//
// Почему используем хэш:
//   - значения стека, IP и времени могут быть длинными;
//   - идентификатор должен быть компактным;
//   - идентификатор должен быть безопасным для отображения в интерфейсе.
//
// Почему используем опорное время:
//   - один и тот же стек может быть у разных ботов;
//   - время первого события помогает различать исторические кластеры;
//   - это не идеальная гарантия, но разумный MVP-уровень.
func ProfileIDFromFingerprint(fp StackFingerprint, seedIP string, seedTime time.Time) string {
	// Приводим опорное время к UTC и обрезаем до часа.
	//
	// Зачем:
	//   - секундные колебания не должны менять ID;
	//   - часовая гранулярность достаточна для первичной привязки;
	//   - это уменьшает фрагментацию профилей при небольшом дрейфе времени.
	seedHour := seedTime.UTC().Truncate(time.Hour).Format(time.RFC3339)

	// Формируем строку-семя.
	//
	// В неё входят:
	//   - все четыре поля стека;
	//   - опорный IP;
	//   - опорный час.
	//
	// Это даёт достаточно уникальности для первого этапа.
	seed := fmt.Sprintf(
		"%d|%d|%d|%d|%s|%s",
		fp.MSS,
		fp.RcvSpace,
		fp.SndWscale,
		fp.RcvWscale,
		seedIP,
		seedHour,
	)

	// Считаем SHA-256 от строки-семени.
	//
	// Нам не нужна криптографическая стойкость как у пароля.
	// Нам нужна компактная, устойчивая и воспроизводимая метка.
	sum := sha256.Sum256([]byte(seed))

	// Берём первые 12 байт хэша.
	//
	// Почему 12:
	//   - достаточно коротко для интерфейса;
	//   - достаточно уникально для локальной аналитики;
	//   - не раздувает веб-таблицы.
	short := sum[:12]

	// Возвращаем человекочитаемый идентификатор.
	//
	// Пример:
	//   AGL_PROFILE_ab12cd34ef56789012345678
	return ProfileIDPrefix + hex.EncodeToString(short)
}

// NewActorProfile создаёт новый профиль из события.
//
// Аргументы:
//   - rec: нормализованное событие.
//
// Возврат:
//   - профиль и true, если профиль можно создать;
//   - nil и false, если данных недостаточно.
//
// Требования для создания профиля:
//   - событие имеет полный сетевой отпечаток;
//   - событие имеет валидный IP;
//   - событие имеет валидное время.
//
// Почему так строго:
//   - профиль без стека не имеет идентификационной основы;
//   - профиль без IP не имеет сетевого якоря;
//   - профиль без времени не имеет жизненного цикла.
func NewActorProfile(rec EventRecord) (*ActorProfile, bool) {
	// Пытаемся извлечь полный сетевой отпечаток.
	//
	// Если отпечаток неполный, профиль не создаём.
	// Это защищает от ложных кластеров на частичных данных.
	fp, ok := StackFingerprintFromEvent(rec)
	if !ok {
		return nil, false
	}

	// Проверяем валидный IP.
	//
	// Без IP профиль не может быть привязан к наблюдаемому актору.
	if !rec.IPValid || rec.IP == "" {
		return nil, false
	}

	// Проверяем валидное время.
	//
	// Без времени профиль не может иметь:
	//   - создан;
	//   - последний раз виден;
	//   - срок жизни.
	if !rec.StartTimeValid {
		return nil, false
	}

	// Приводим время к UTC.
	//
	// Все временные метки профиля храним в UTC.
	// Это исключает локальные таймзонные искажения.
	seedTime := rec.StartTime.UTC()

	// Создаём базовый профиль.
	//
	// Сразу инициализируем все карты,
	// чтобы дальнейшие добавления событий были безопасными.
	profile := &ActorProfile{
		ID:         ProfileIDFromFingerprint(fp, rec.IP, seedTime),
		Stack:      fp,
		StackValid: true,
		State:      ProfileStateActive,

		CreatedAt: seedTime,
		UpdatedAt: seedTime,
		LastSeen:  seedTime,
		ExpiresAt: seedTime.Add(DefaultProfileTTL),

		FirstEventTime: seedTime,
		LastEventTime:  seedTime,

		IPCounts:          make(map[string]int),
		CountryCounts:     make(map[string]int),
		BehaviorCounts:    make(map[string]int),
		CloseReasonCounts: make(map[string]int),
		LinkedIPCounts:    make(map[string]int),

		Evidence: []string{},
		Reasons:  []string{},

		TTL: DefaultProfileTTL,
	}

	// Оцениваем стартовую уверенность по редкости стека.
	//
	// Если стек распространённый, стартовая уверенность ниже.
	// Если стек более редкий, стартовая уверенность выше.
	//
	// Это осознанная эвристика.
	// Она не заменяет будущую калибровку, но даёт честный старт.
	if isCommonStack(fp) {
		// Распространённый профиль.
		//
		// Такой профиль может совпадать у многих ботов одного билда,
		// у контейнеров или у стандартных туннелей.
		//
		// Поэтому стартуем осторожно.
		profile.Confidence = 35
		profile.FalsePositiveRisk = FalsePositiveRiskHigh

		// Сразу фиксируем предупреждение.
		//
		// Администратор должен видеть, что профиль массовый.
		profile.Evidence = append(
			profile.Evidence,
			"обнаружен распространённый сетевой профиль",
		)
	} else {
		// Более редкий профиль.
		//
		// Это не гарантия уникальности, но такой профиль
		// обычно даёт меньше случайных совпадений.
		profile.Confidence = 55
		profile.FalsePositiveRisk = FalsePositiveRiskMedium
	}

	// Добавляем исходное событие в профиль.
	//
	// Это заполнит базовые счётчики:
	//   - IP;
	//   - страна;
	//   - поведение;
	//   - CloseReason;
	//   - RTT;
	//   - план/факт.
	profile.AddEvent(rec)

	// Возвращаем готовый профиль.
	//
	// Он уже имеет:
	//   - ID;
	//   - стек;
	//   - состояние;
	//   - стартовую уверенность;
	//   - первое событие.
	return profile, true
}

// ensureMaps проверяет и создаёт внутренние карты профиля.
//
// Зачем:
//   - профиль может быть создан вручную в тестах;
//   - профиль может быть десериализован из внешнего источника;
//   - мы должны защититься от записи в nil-карту.
//
// Метод идемпотентен:
//   - если карты уже созданы, ничего не меняется;
//   - если карты пустые, они создаются.
func (p *ActorProfile) ensureMaps() {
	// Защита от вызова на пустом указателе.
	//
	// Если профиль не существует, просто выходим.
	// Это безопаснее, чем паника.
	if p == nil {
		return
	}

	// Создаём карту IP, если её нет.
	//
	// Эта карта нужна для учёта фактических наблюдений.
	if p.IPCounts == nil {
		p.IPCounts = make(map[string]int)
	}

	// Создаём карту стран, если её нет.
	//
	// Эта карта нужна для географической динамики.
	if p.CountryCounts == nil {
		p.CountryCounts = make(map[string]int)
	}

	// Создаём карту поведения, если её нет.
	//
	// Эта карта нужна для оценки агрессии и пассивности.
	if p.BehaviorCounts == nil {
		p.BehaviorCounts = make(map[string]int)
	}

	// Создаём карту причин закрытия, если её нет.
	//
	// Эта карта нужна для психологии удержания.
	if p.CloseReasonCounts == nil {
		p.CloseReasonCounts = make(map[string]int)
	}

	// Создаём карту связанных IP, если её нет.
	//
	// Эта карта нужна для матчей и будущих слияний.
	if p.LinkedIPCounts == nil {
		p.LinkedIPCounts = make(map[string]int)
	}

	// Создаём список доказательств, если его нет.
	//
	// Это защищает от добавления в nil-срез.
	if p.Evidence == nil {
		p.Evidence = []string{}
	}

	// Создаём список причин, если его нет.
	//
	// Это защищает от добавления в nil-срез.
	if p.Reasons == nil {
		p.Reasons = []string{}
	}
}

// AddEvent добавляет событие в профиль.
//
// Аргументы:
//   - rec: нормализованное событие.
//
// Поведение:
//   - увеличиваются счётчики;
//   - обновляются временные границы;
//   - обновляются RTT и план/факт;
//   - проверяется совместимость стека;
//   - при противоречиях снижается уверенность.
//
// Важно:
//   - метод не проверяет, принадлежит ли событие профилю по мнению менеджера;
//   - это задача будущего ProfileManager;
//   - здесь мы только безопасно обновляем состояние профиля.
func (p *ActorProfile) AddEvent(rec EventRecord) {
	// Защита от вызова на пустом указателе.
	//
	// Если профиль не существует, просто выходим.
	// Это безопаснее, чем паника.
	if p == nil {
		return
	}

	// Гарантируем, что все внутренние структуры готовы.
	//
	// Это нужно перед любой записью в карты и срезы.
	p.ensureMaps()

	// Увеличиваем общее количество событий.
	//
	// Это базовый счётчик активности профиля.
	p.EventCount++

	// Разделяем события на валидные и невалидные.
	//
	// Валидность уже определена нормализатором.
	// Мы только учитываем её в профиле.
	if rec.Valid {
		p.ValidEventCount++
	} else {
		p.InvalidEventCount++
	}

	// Обновляем временные метки, если время события валидно.
	//
	// Если времени нет, событие всё равно учитывается,
	// но не двигает временную линию профиля.
	if rec.StartTimeValid {
		// Приводим время к UTC.
		//
		// Все временные метки профиля храним в UTC.
		t := rec.StartTime.UTC()

		// Обновляем первую временную границу.
		//
		// Если это самое раннее событие, запоминаем его как первое.
		if p.FirstEventTime.IsZero() || t.Before(p.FirstEventTime) {
			p.FirstEventTime = t
		}

		// Обновляем последнюю временную границу.
		//
		// Если это самое позднее событие, запоминаем его как последнее.
		if p.LastEventTime.IsZero() || t.After(p.LastEventTime) {
			p.LastEventTime = t
		}

		// Двигаем время последней активности.
		//
		// Это влияет на TTL и состояние просрочки.
		p.advanceTime(t)
	}

	// Учитываем IP, если он валиден и не пуст.
	//
	// Это фактические наблюдения профиля.
	//
	// Почему только валидные:
	//   - битые IP не должны влиять на уникальные адреса;
	//   - повреждённые данные уже видны в счётчиках качества.
	if rec.IPValid && rec.IP != "" {
		p.IPCounts[rec.IP]++
	}

	// Учитываем страну, если она не пустая.
	//
	// Пустая страна означает отсутствие данных.
	// Мы не превращаем её в отдельную сущность.
	if rec.Country != "" {
		p.CountryCounts[rec.Country]++
	}

	// Учитываем поведение.
	//
	// Если поведение не распознано, используем UNKNOWN.
	//
	// Это честно:
	//   - мы не выдумываем пассивность или агрессию;
	//   - но показываем, что маркер отсутствовал.
	behavior := rec.Behavior
	if behavior == "" {
		behavior = "UNKNOWN"
	}
	p.BehaviorCounts[behavior]++

	// Учитываем причину закрытия.
	//
	// Если причина пустая, используем UNKNOWN.
	//
	// Это честно:
	//   - мы не выдумываем FIN или RST;
	//   - но показываем, что маркер закрытия отсутствовал.
	closeReason := rec.CloseReason
	if closeReason == "" {
		closeReason = "UNKNOWN"
	}
	p.CloseReasonCounts[closeReason]++

	// Учитываем RTT, если он валиден.
	//
	// Мы не пытаемся угадывать отсутствующий RTT.
	// Если RTT нет, он просто не участвует в агрегатах.
	if rec.RTTValid {
		// Увеличиваем количество валидных RTT.
		p.RTTCount++

		// Добавляем значение к сумме для среднего.
		//
		// Приводим к uint64, чтобы снизить риск переполнения.
		p.RTTSumMs += uint64(rec.RTTMs)

		// Если это первый валидный RTT, принимаем его как минимум и максимум.
		if p.RTTCount == 1 {
			p.RTTMinMs = rec.RTTMs
			p.RTTMaxMs = rec.RTTMs
		} else {
			// Если история уже есть, обновляем минимум и максимум.
			//
			// Это даёт диапазон по всему профилю.
			if rec.RTTMs < p.RTTMinMs {
				p.RTTMinMs = rec.RTTMs
			}
			if rec.RTTMs > p.RTTMaxMs {
				p.RTTMaxMs = rec.RTTMs
			}
		}
	}

	// Алгоритм 2: Сохраняем криминалистические данные токена в профиль.
	//
	// Если событие принесло валидный дрейф или порт, обновляем профиль.
	// Это нужно для детекции "Единого таймера C2" и "Эстафеты портов".
	if rec.TokenTimeDriftValid {
		p.TokenDriftMs = rec.TokenTimeDriftMs
		p.TokenDriftValid = true
	}
	if rec.TokenClientPortValid {
		p.TokenClientPort = rec.TokenClientPort
	}

	// --- АЛГОРИТМ 3: Автоматическая классификация фазы угрозы ---
	// Прогоняем событие через классификатор фаз.
	// Он анализирует ReadTiny/Small/Medium/Large и CloseReason.
	phaseResult := ClassifyPhase(rec)

	// Сохраняем вердикт в профиль.
	// Мы перезаписываем фазу каждый раз, так как она отражает текущее состояние сессии.
	p.CurrentPhase = phaseResult.Label
	p.ThreatLevel = phaseResult.DangerLevel

	// --- АЛГОРИТМ 4: Оценка прогноза будущего поведения ---
	// Сравниваем текущую сессию с предыдущей, зафиксированной в профиле.
	currentPayload := rec.ReadLarge + rec.ReadMedium
	deltaPayload := int64(currentPayload) - int64(p.lastPayloadSize)

	attackInterval := time.Duration(0)
	if !p.lastSessionTime.IsZero() && rec.StartTimeValid {
		attackInterval = rec.StartTime.Sub(p.lastSessionTime)
	}

	// Вычисляем прогноз на основе правил из спецификации
	if deltaPayload > 0 && p.lastCloseReason == "TIMEOUT" && rec.CloseReason == "FIN" {
		p.PredictedVector = "Целевой брутфорс / Эксплуатация L7-уязвимости"
		p.PredictedProbability = "90% в течение 30 минут"
	} else if attackInterval > 0 && attackInterval < 5*time.Minute && rec.Behavior == "AGGRESSIVE" {
		// Упрощение для MVP: интервал мал (< 5 мин) и поведение агрессивное
		p.PredictedVector = "Массированный DDoS / Забивание пула сокетов"
		p.PredictedProbability = "85% в течение 1 часа"
	} else {
		p.PredictedVector = "Фоновый непрерывный скан периметра"
		p.PredictedProbability = "Низкая"
	}

	// Обновляем "предыдущие" значения для оценки следующей сессии
	p.lastSessionTime = rec.StartTime
	p.lastPayloadSize = currentPayload
	p.lastCloseReason = rec.CloseReason

	// Учитываем пару план/факт только если оба значения валидны.
	//
	// Почему вместе:
	//   - план без факта не даёт полной картины удержания;
	//   - факт без плана не даёт понять дельту;
	//   - для психологии удержания нужны оба значения.
	if rec.PlannedHoldValid && rec.ActualHoldValid {
		p.PlannedHoldSumSec += rec.PlannedHoldSec
		p.ActualHoldSumSec += rec.ActualHoldSec
		p.HoldCount++
	}

	// Проверяем совместимость стека.
	//
	// Это важный контроль качества профиля.
	//
	// Если событие имеет полный стек, но он не совпадает со стеком профиля,
	// значит профиль получил противоречивое наблюдение.
	//
	// Мы не удаляем событие, но снижаем уверенность и фиксируем причину.
	if eventStack, ok := StackFingerprintFromEvent(rec); ok {
		// Если у профиля ещё нет стека, принимаем стек события.
		//
		// Это защитный механизм.
		// В нормальном потоке профиль уже создаётся со стеком.
		if !p.StackValid {
			p.Stack = eventStack
			p.StackValid = true
		} else if !CompareStack(p.Stack, eventStack) {
			// Стек события не совпадает со стеком профиля.
			//
			// Это противоречие.
			//
			// Возможные причины:
			//   - менеджер ошибочно привязал событие;
			//   - профиль начал распадаться;
			//   - бот меняет сетевые параметры;
			//   - данные повреждены.
			//
			// Мы обязаны это зафиксировать.

			// Понижаем уверенность.
			//
			// Противоречивый стек не должен укреплять профиль.
			p.Confidence = clampConfidence(p.Confidence - 5)

			// Повышаем риск ложной склейки.
			//
			// Если внутри профиля появляются разные стеки,
			// гипотеза становится менее надёжной.
			p.FalsePositiveRisk = worseFalsePositiveRisk(
				p.FalsePositiveRisk,
				FalsePositiveRiskHigh,
			)

			// Добавляем причину.
			//
			// Администратор должен видеть противоречие.
			p.Reasons = appendUnique(
				p.Reasons,
				"обнаружено событие с несовпадающим сетевым стеком",
			)
		}
	}

	// Обновляем состояние профиля по текущей уверенности.
	//
	// Если уверенность упала ниже порога,
	// профиль должен быть помечен как низкоуверенный.
	p.updateStateByConfidence()
}

// advanceTime продвигает время последней активности профиля.
//
// Аргументы:
//   - t: время события в UTC.
//
// Поведение:
//   - обновляет UpdatedAt;
//   - обновляет LastSeen только если время новее текущего;
//   - пересчитывает ExpiresAt;
//   - возвращает просроченный профиль в активное состояние,
//     если появилась новая активность.
//
// Важно:
//   - старые события не должны продлевать срок жизни;
//   - старые события не должны двигать LastSeen назад.
func (p *ActorProfile) advanceTime(t time.Time) {
	// Защита от вызова на пустом указателе.
	//
	// Если профиль не существует, просто выходим.
	if p == nil {
		return
	}

	// Обновляем время последнего изменения.
	//
	// Это нужно для аудита и отладки.
	// Даже старое событие меняет профиль, поэтому UpdatedAt двигаем.
	p.UpdatedAt = t

	// Если время события новее текущего LastSeen, продвигаем активность.
	//
	// Это защищает от ситуации, когда старые логи
	// искусственно омолаживают просроченный профиль.
	if p.LastSeen.IsZero() || t.After(p.LastSeen) {
		// Запоминаем новую последнюю активность.
		p.LastSeen = t

		// Если TTL не задан, используем значение по умолчанию.
		//
		// Это защитный механизм.
		// Профиль не должен жить с нулевым или отрицательным TTL.
		if p.TTL <= 0 {
			p.TTL = DefaultProfileTTL
		}

		// Пересчитываем срок истечения.
		//
		// Формула простая:
		//   последняя активность + TTL.
		p.ExpiresAt = t.Add(p.TTL)

		// Если профиль был просрочен, но появилась новая активность,
		// возвращаем его в активное состояние.
		//
		// Это справедливо только для просроченных профилей.
		// Объединённые и разделённые профили не должны автоматически оживать.
		if p.State == ProfileStateExpired {
			p.State = ProfileStateActive
		}
	}
}

// IsExpired проверяет, просрочен ли профиль.
//
// Аргументы:
//   - now: текущее время проверки.
//
// Возврат:
//   - true, если профиль просрочен;
//   - false иначе.
//
// Важно:
//   - профиль без срока истечения не считается просроченным;
//   - проверка не меняет состояние профиля.
//
// Решение о переводе в EXPIRED принимает менеджер профилей.
func (p *ActorProfile) IsExpired(now time.Time) bool {
	// Защита от вызова на пустом указателе.
	//
	// Пустой профиль считаем просроченным, чтобы не использовать его.
	// Это консервативный подход.
	if p == nil {
		return true
	}

	// Если срок истечения не задан, профиль не просрочен.
	//
	// Это защитный механизм.
	// Мы не хотим молча убивать профили без настроенного TTL.
	if p.ExpiresAt.IsZero() {
		return false
	}

	// Профиль просрочен, если текущее время позже срока истечения.
	//
	// Используем After, а не Before, чтобы граница была понятной:
	//   - ровно в ExpiresAt профиль ещё не просрочен;
	//   - после ExpiresAt профиль просрочен.
	return now.After(p.ExpiresAt)
}

// AddMatchEvidence добавляет результат идентификации в профиль.
//
// Аргументы:
//   - result: результат сравнения текущего и архивного события.
//
// Поведение:
//   - учитывает связанный архивный IP;
//   - добавляет доказательства и причины;
//   - повышает уверенность при сильных матчах;
//   - повышает риск ложной склейки при необходимости;
//   - обновляет состояние по уверенности.
//
// Важно:
//   - метод не создаёт новые профили;
//   - метод не объединяет профили автоматически;
//   - он только накапливает свидетельства.
func (p *ActorProfile) AddMatchEvidence(result MatchResult) {
	// Защита от вызова на пустом указателе.
	//
	// Если профиль не существует, просто выходим.
	if p == nil {
		return
	}

	// Гарантируем, что все внутренние структуры готовы.
	//
	// Это нужно перед записью в карты и срезы.
	p.ensureMaps()

	// Определяем время матча.
	//
	// Берём более позднее из двух времён:
	//   - текущего события;
	//   - архивного события.
	//
	// Это нужно, чтобы матч мог продлить активность профиля,
	// если он ссылается на более свежее событие.
	matchTime := result.CurrentTime
	if result.ArchiveTime.After(matchTime) {
		matchTime = result.ArchiveTime
	}

	// Если время матча валидно, продвигаем время активности.
	//
	// Если время нулевое или невалидное, не двигаем LastSeen.
	// Это защищает от ложного омоложения профиля.
	if !matchTime.IsZero() {
		p.advanceTime(matchTime.UTC())
	}

	// Учитываем архивный IP как связанный.
	//
	// Это не фактическое событие, но это свидетельствование того,
	// что другой IP имеет похожий профиль.
	//
	// Позже это поможет строить карту ротации.
	if result.ArchiveIP != "" {
		p.LinkedIPCounts[result.ArchiveIP]++
	}

	// Добавляем доказательства из результата матча.
	//
	// Используем добавление без дублей, чтобы веб-панель
	// не засорялась одинаковыми строками при повторных матчах.
	for _, evidence := range result.Evidence {
		p.Evidence = appendUnique(p.Evidence, evidence)
	}

	// Добавляем причины из результата матча.
	//
	// Используем добавление без дублей, чтобы список оставался читаемым.
	for _, reason := range result.Reasons {
		p.Reasons = appendUnique(p.Reasons, reason)
	}

	// Если матч вообще дал ненулевой сигнал, слегка повышаем уверенность.
	//
	// Это поощряет накопление совпадений, но не делает это слишком резко.
	//
	// Один матч не должен превращать слабый профиль в сильный.
	if result.Score > 0 {
		p.Confidence = clampConfidence(p.Confidence + 2)
	}

	// Если матч разрешает связку, повышаем уверенность сильнее.
	//
	// Это означает, что сработали оба условия:
	//   - достаточный Score;
	//   - достаточный Confidence.
	//
	// Такой матч является серьёзным подтверждением профиля.
	if result.ShouldLink {
		p.Confidence = clampConfidence(p.Confidence + 5)

		// Добавляем пояснение.
		//
		// Администратор должен видеть, что профиль получил связку.
		p.Reasons = appendUnique(
			p.Reasons,
			"получено подтверждение связки через идентификацию",
		)
	}

	// Если Score высокий, но связка не разрешена, фиксируем это отдельно.
	//
	// Это важная диагностика:
	//   - формально признаки сильные;
	//   - но фактическая уверенность недостаточна;
	//   - значит есть дополнительные риски.
	//
	// Такой случай должен быть виден в интерфейсе.
	if result.Score >= LinkScoreThreshold && !result.ShouldLink {
		p.Reasons = appendUnique(
			p.Reasons,
			"высокий алгоритмический балл, но недостаточная фактическая уверенность",
		)
	}

	// Учитываем риск ложной склейки из результата матча.
	//
	// Если результат приносит более высокий риск, профиль должен это унаследовать.
	//
	// Это консервативный подход:
	// риск должен расти при сомнениях, а не исчезать молча.
	p.FalsePositiveRisk = worseFalsePositiveRisk(
		p.FalsePositiveRisk,
		result.FalsePositiveRisk,
	)

	// Обновляем состояние профиля по текущей уверенности.
	//
	// Если уверенность упала, профиль может стать низкоуверенным.
	// Если уверенность выросла, профиль может вернуться в активное состояние.
	p.updateStateByConfidence()
}

// updateStateByConfidence обновляет состояние профиля по уверенности.
//
// Поведение:
//   - если уверенность ниже порога, профиль становится LOW_CONFIDENCE;
//   - если уверенность выше порога, профиль становится ACTIVE;
//   - профили в состояниях MERGED, SPLIT и EXPIRED не меняются здесь.
//
// Почему так:
//   - объединённые и разделённые профили имеют особый жизненный цикл;
//   - просроченный профиль должен оживать через новую активность,
//     а не через простое изменение уверенности.
func (p *ActorProfile) updateStateByConfidence() {
	// Защита от вызова на пустом указателе.
	//
	// Если профиль не существует, просто выходим.
	if p == nil {
		return
	}

	// Не трогаем особые состояния.
	//
	// Эти состояния управляются отдельными механизмами:
	//   - слияние;
	//   - разделение;
	//   - просрочка и новая активность.
	//
	// Обычная уверенность не должна их перезаписывать.
	if p.State == ProfileStateMerged ||
		p.State == ProfileStateSplit ||
		p.State == ProfileStateExpired {
		return
	}

	// Если уверенность ниже порога, помечаем профиль как низкоуверенный.
	//
	// Такой профиль можно показывать, но нельзя считать сильным.
	if p.Confidence < ProfileLowConfidenceThreshold {
		p.State = ProfileStateLowConfidence
		return
	}

	// Если уверенность достаточная, возвращаем профиль в активное состояние.
	//
	// Это позволяет профилю восстановиться после временных сомнений.
	p.State = ProfileStateActive
}

// AvgPlannedHoldSec возвращает среднее запланированное время удержания для профиля.
