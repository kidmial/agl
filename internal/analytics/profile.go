// appendUnique добавляет строку в срез только если её там ещё нет.
//
// Аргументы:
//   - slice: исходный срез;
//   - value: строка для добавления.
//
// Возврат:
//   - исходный срез, если строка уже есть;
//   - новый срез с добавленной строкой, если строки не было.
//
// Зачем:
//   - доказательства не должны дублироваться при повторных матчах;
//   - причины не должны засорять интерфейс одинаковыми фразами;
//   - списки остаются читаемыми и компактными.
func appendUnique(slice []string, value string) []string {
	// Проходим по существующим элементам.
	//
	// Это линейный поиск.
	// Для небольших списков доказательств этого достаточно.
	//
	// Если списки станут большими, можно будет заменить на map.
	for _, existing := range slice {
		// Если строка уже есть, возвращаем исходный срез без изменений.
		//
		// Это предотвращает дублирование.
		if existing == value {
			return slice
		}
	}

	// Если строки не было, добавляем её.
	//
	// Возвращаем новый срез, потому что append может расширить ёмкость.
	// Вызывающий код обязан использовать возвращаемое значение.
	return append(slice, value)
}

// clampConfidence ограничивает уверенность допустимыми пределами.
//
// Аргументы:
//   - value: сырое значение уверенности.
//
// Возврат:
//   - значение в диапазоне от ProfileConfidenceMin до ProfileConfidenceMax.
//
// Зачем:
//   - уверенность не должна быть отрицательной;
//   - уверенность не должна достигать 100%;
//   - даже сильные гипотезы остаются гипотезами.
func clampConfidence(value int) int {
	// Если значение ниже минимума, возвращаем минимум.
	//
	// Отрицательная уверенность не имеет смысла.
	if value < ProfileConfidenceMin {
		return ProfileConfidenceMin
	}

	// Если значение выше максимума, возвращаем максимум.
	//
	// Мы сознательно не разрешаем 100%.
	// Это архитектурная защита от ложного абсолюта.
	if value > ProfileConfidenceMax {
		return ProfileConfidenceMax
	}

	// Значение находится в допустимых пределах.
	//
	// Возвращаем его без изменений.
	return value
}

// falsePositiveRiskRank возвращает числовой ранг риска ложной склейки.
//
// Аргументы:
//   - risk: строковый уровень риска.
//
// Возврат:
//   - числовой ранг для сравнения.
//
// Зачем:
//   - строковые уровни удобно сравнивать через ранги;
//   - код становится читаемым;
//   - легко расширять шкалу в будущем.
func falsePositiveRiskRank(risk string) int {
	switch risk {
	case FalsePositiveRiskNone:
		// Риск отсутствует или не оценивался.
		//
		// Это нулевой уровень.
		return 0

	case FalsePositiveRiskLow:
		// Низкий риск.
		//
		// Это первый уровень реальной оценки.
		return 1

	case FalsePositiveRiskMedium:
		// Средний риск.
		//
		// Это второй уровень.
		// Обычно означает распространённый профиль или неполные данные.
		return 2

	case FalsePositiveRiskHigh:
		// Высокий риск.
		//
		// Это третий уровень.
		// Обычно означает серьёзные сомнения в связке.
		return 3

	default:
		// Неизвестный уровень риска трактуем как высокий.
		//
		// Это консервативный подход.
		// Лучше переоценить риск, чем скрыть сомнения.
		return 3
	}
}

// worseFalsePositiveRisk выбирает более высокий риск из двух.
//
// Аргументы:
//   - a: текущий риск;
//   - b: входящий риск.
//
// Возврат:
//   - более высокий уровень риска.
//
// Зачем:
//   - профиль должен наследовать сомнения из матчей;
//   - риск не должен молча уменьшаться при появлении новых данных;
//   - это консервативная политика честной форензики.
func worseFalsePositiveRisk(a string, b string) string {
	// Получаем числовые ранги обоих уровней.
	//
	// Это позволяет сравнивать строковые уровни безопасно.
	rankA := falsePositiveRiskRank(a)
	rankB := falsePositiveRiskRank(b)

	// Если входящий риск выше, возвращаем его.
	//
	// Это означает, что новые данные принесли больше сомнений.
	if rankB > rankA {
		return b
	}

	// Иначе оставляем текущий риск.
	//
	// Если риски равны, также оставляем текущий.
	// Это не меняет состояние и сохраняет стабильность.
	return a
}

