package analytics

import (
	"fmt"
	"sync"
	"time"
)

// DefaultStoreCapacity задаёт ёмкость кольцевого буфера по умолчанию.
//
// Почему не бесконечность:
//   - аналитика работает в оперативной памяти;
//   - комплекс должен оставаться лёгким;
//   - старые события важны, но не должны вытеснять свободную память.
//
// Значение можно будет позже вынести в конфигурацию.
// Пока это безопасный рабочий ориентир.
const DefaultStoreCapacity = 10000

// StoreCounters содержит служебные счётчики хранилища.
//
// Это нужно для:
//   - веб-панели;
//   - диагностики;
//   - контроля качества данных;
//   - понимания, сколько событий реально хранится и обработано.
type StoreCounters struct {
	// Capacity — максимальная ёмкость кольцевого буфера.
	//
	// Это не количество обработанных событий, а только лимит памяти.
	Capacity int

	// Stored — сколько событий сейчас находится в кольцевом буфере.
	//
	// Если событий больше ёмкости, старые вытесняются.
	Stored int

	// TotalEvents — сколько событий прошло через хранилище за всё время.
	//
	// Сюда входят:
	//   - валидные события;
	//   - невалидные события;
	//   - события с проблемами качества данных.
	TotalEvents int64

	// ValidEvents — сколько событий прошли нормализацию без ошибок.
	//
	// Именно такие события позже будут использоваться для статистики.
	ValidEvents int64

	// InvalidEvents — сколько событий имели хотя бы одну проблему качества.
	//
	// Эти события не должны молча попадать в агрегаты.
	// Они должны быть видны в отчёте качества данных.
	InvalidEvents int64

	// IssueCount — суммарное количество проблем качества данных.
	//
	// Одно событие может иметь несколько проблем.
	// Например:
	//   - битое время;
	//   - пустой токен;
	//   - неверный порт.
	//
	// Поэтому IssueCount может быть больше, чем InvalidEvents.
	IssueCount int64

	// HasEventTime показывает, что в хранилище есть хотя бы одно событие
	// с успешно разобранным временем.
	//
	// Если времени нет, временные агрегаты строить нельзя.
	HasEventTime bool

	// FirstEventTime — самое раннее время среди событий с валидным временем.
	//
	// Значение имеет смысл только если HasEventTime == true.
	FirstEventTime time.Time

	// LastEventTime — самое позднее время среди событий с валидным временем.
	//
	// Значение имеет смысл только если HasEventTime == true.
	LastEventTime time.Time

	// --- ДИАГНОСТИКА ИНЖЕСТА ---
	// ingestPath — путь к логу, который читает инжест.
	ingestPath string

	// ingestStarted — запущен ли инжест.
	ingestStarted bool

	// ingestBrokenLines — количество строк, отброшенных как битые.
	ingestBrokenLines uint64

	// ingestLastErrors — последние 5 ошибок парсинга (для диагностики).
	ingestLastErrors []string
}

// Store — основное оперативное хранилище аналитики.
//
// Ответственность:
//   - принимать нормализованные события;
//   - хранить их в ограниченном кольцевом буфере;
//   - вести счётчики качества;
//   - отдавать снимки данных для веб-панели и агрегаторов.
//
// Важно:
//   - Store не парсит файлы напрямую;
//   - Store не строит прогнозы;
//   - Store не принимает архитектурных решений;
//   - Store только безопасно хранит уже обработанные события.
type Store struct {
	// mu защищает все внутренние поля хранилища.
	//
	// Почему используем RWMutex:
	//   - добавление событий требует эксклюзивной блокировки;
	//   - чтение снимков может происходить параллельно;
	//   - веб-панель будет часто читать, но реже писать.
	mu sync.RWMutex

	// capacity — ёмкость кольцевого буфера.
	//
	// После создания хранилища ёмкость не меняется.
	// Это упрощает логику и исключает динамические миграции памяти.
	capacity int

	// ring — кольцевой буфер событий.
	//
	// Почему кольцо:
	//   - фиксированная память;
	//   - новые события вытесняют самые старые;
	//   - не нужно перекладывать весь срез при каждом добавлении.
	ring []EventRecord

	// head — индекс, куда будет записано следующее событие.
	//
	// После каждой записи head сдвигается вперёд.
	// Когда достигается конец буфера, индекс возвращается в начало.
	head int

	// size — сколько ячеек кольца сейчас занято.
	//
	// Пока буфер не заполнен, size растёт.
	// После заполнения размер остаётся равным capacity.
	size int

	// totalEvents — сколько всего событий прошло через AddEvent.
	//
	// Этот счётчик не уменьшается при вытеснении старых событий.
	// Он показывает общий объём обработанного материала.
	totalEvents int64

	// validEvents — сколько валидных событий прошло через AddEvent.
	//
	// Валидные события позже используются для статистики.
	validEvents int64

	// invalidEvents — сколько невалидных событий прошло через AddEvent.
	//
	// Эти события нужны для контроля качества, но не для агрегатов.
	invalidEvents int64

	// issueCount — сколько всего проблем качества данных обнаружено.
	//
	// Одно событие может дать несколько проблем.
	// Поэтому счётчик считает именно проблемы, а не только события.
	issueCount int64

	// hasEventTime показывает, что мы уже видели хотя бы одно событие
	// с валидным временем.
	//
	// Это нужно, чтобы корректно интерпретировать первое/последнее время.
	hasEventTime bool

	// firstEventTime — самое раннее валидное время события.
	//
	// Обновляется только если событие имеет валидное время.
	// Битые значения времени не должны двигать временные границы.
	firstEventTime time.Time

	// lastEventTime — самое позднее валидное время события.
	//
	// Обновляется только если событие имеет валидное время.
	// Битые значения времени не должны двигать временные границы.
	lastEventTime time.Time

	// --- ДИАГНОСТИКА ИНЖЕСТА ---
	// ingestPath — путь к логу, который читает инжест.
	ingestPath string

	// ingestStarted — запущен ли инжест.
	ingestStarted bool

	// ingestBrokenLines — количество строк, отброшенных как битые.
	ingestBrokenLines uint64

	// ingestLastErrors — последние 5 ошибок парсинга (для диагностики).
	ingestLastErrors []string
}

// NewStore создаёт новое хранилище аналитики.
//
// Аргументы:
//   - capacity: максимальное количество событий в кольцевом буфере.
//
// Если передано неположительное значение, используется ёмкость по умолчанию.
//
// Возврат:
//   - готовый к работе Store.
//
// Почему возвращаем указатель:
//   - Store содержит мьютекс;
//   - его нельзя бездумно копировать;
//   - все методы работают с одним общим состоянием.
func NewStore(capacity int) *Store {
	// Если ёмкость не задана или задана некорректно,
	// используем безопасное значение по умолчанию.
	//
	// Это защищает от случайного создания нулевого или отрицательного буфера.
	if capacity <= 0 {
		capacity = DefaultStoreCapacity
	}

	// Создаём хранилище.
	//
	// Кольцевой буфер сразу выделяем нужного размера.
	// Дальше он не расширяется.
	//
	// Это осознанное решение:
	//   - предсказуемая память;
	//   - нет внезапных аллокаций при росте;
	//   - старые события вытесняются, а не копят диск/память.
	return &Store{
		capacity: capacity,
		ring:     make([]EventRecord, capacity),
		head:     0,
		size:     0,
	}
}

// AddEvent добавляет одно нормализованное событие в хранилище.
//
// Аргументы:
//   - rec: событие, уже прошедшее нормализацию.
//
// Поведение:
//   - событие попадает в кольцевой буфер;
//   - счётчики качества обновляются;
//   - при переполнении вытесняется самое старое событие;
//   - метод потокобезопасен.
//
// Почему метод принимает уже нормализованное событие:
//   - Store не должен знать детали парсинга;
//   - Store не должен решать, как интерпретировать сырые поля;
//   - нормализация уже выполнена в NormalizeEvent.
func (s *Store) AddEvent(rec EventRecord) {
	// Захватываем эксклюзивную блокировку.
	//
	// Мы будем менять:
	//   - кольцевой буфер;
	//   - индексы;
	//   - счётчики;
	//   - временные границы.
	//
	// Параллельная запись без блокировки привела бы к гонке.
	s.mu.Lock()

	// Гарантируем освобождение блокировки при выходе.
	//
	// Даже если внутри произойдёт логическая ошибка,
	// мьютекс должен быть освобождён.
	defer s.mu.Unlock()

	// Увеличиваем общий счётчик событий.
	//
	// Этот счётчик учитывает все события, даже битые.
	// Он нужен для общей статистики обработки.
	s.totalEvents++

	// Разделяем события на валидные и невалидные.
	//
	// Валидность определяется нормализатором.
	// Если у события есть хотя бы одна проблема качества,
	// оно считается невалидным для агрегатов.
	if rec.Valid {
		// Событие прошло нормализацию без ошибок.
		//
		// Такие события будут основой для:
		//   - часовых срезов;
		//   - профилей;
		//   - кластеров;
		//   - поведенческой аналитики.
		s.validEvents++
	} else {
		// Событие имеет проблемы качества.
		//
		// Мы всё равно храним его в буфере, потому что:
		//   - оно может быть полезно для диагностики;
		//   - администратор должен видеть повреждённые строки;
		//   - честная статистика должна показывать не только успехи.
		s.invalidEvents++

		// Увеличиваем счётчик проблем качества.
		//
		// Одно событие может содержать несколько проблем.
		// Например:
		//   - пустой токен;
		//   - неверный IP;
		//   - битое время.
		//
		// Поэтому прибавляем количество проблем, а не единицу.
		s.issueCount += int64(len(rec.Issues))
	}

	// Обновляем временные границы только если время события валидно.
	//
	// Почему так:
	//   - битое время не должно создавать ложную временную шкалу;
	//   - события без времени не могут участвовать во временных агрегатах;
	//   - но они всё равно учитываются в счётчиках качества.
	if rec.StartTimeValid {
		// Если это первое валидное время, просто принимаем его как границу.
		//
		// Пока нет истории, не с чем сравнивать.
		if !s.hasEventTime {
			s.firstEventTime = rec.StartTime
			s.lastEventTime = rec.StartTime
			s.hasEventTime = true
		} else {
			// Если время раньше текущего первого, обновляем первую границу.
			//
			// Это может произойти при разборе старых логов
			// или при нестрого хронологическом поступлении событий.
			if rec.StartTime.Before(s.firstEventTime) {
				s.firstEventTime = rec.StartTime
			}

			// Если время позже текущего последнего, обновляем последнюю границу.
			//
			// Это типичная ситуация для живого потока событий.
			if rec.StartTime.After(s.lastEventTime) {
				s.lastEventTime = rec.StartTime
			}
		}
	}

	// Записываем событие в текущую позицию кольца.
	//
	// Если буфер уже заполнен, эта операция перезапишет самое старое событие.
	// Это нормальное поведение кольцевого буфера.
	s.ring[s.head] = rec

	// Сдвигаем голову на следующую позицию.
	//
	// Это делается вручную, а не через оператор %,
	// чтобы избежать лишнего деления в горячем пути.
	s.head++

	// Если достигли конца буфера, возвращаемся в начало.
	//
	// Кольцо замыкается.
	// Следующая запись снова пойдёт в нулевую ячейку.
	if s.head == s.capacity {
		s.head = 0
	}

	// Увеличиваем заполненный размер, если буфер ещё не полон.
	//
	// После заполнения размер остаётся равным ёмкости.
	//
	// Это важно для снимков:
	//   - если размер меньше ёмкости, в кольце есть пустые ячейки;
	//   - если размер равен ёмкости, в кольце находятся только события.
	if s.size < s.capacity {
		s.size++
	}
	// Инкремент колец агрегатной отчётности (v8.6.2).
	// Вызываем под блокировкой Store, чтобы бакеты и кольцо были согласованы.
	if GlobalRollup != nil {
		GlobalRollup.Ingest(rec)
	}
}

// AddRaw принимает сырое событие, нормализует его и добавляет в хранилище.
//
// Аргументы:
//   - raw: сырое событие, полученное из парсера.
//
// Возврат:
//   - нормализованное событие, которое было добавлено.
//
// Зачем этот метод:
//   - связывает парсер, нормализатор и хранилище одной короткой операцией;
//   - удобен для инжеста файлов;
//   - позволяет вызывающему коду при желании проверить результат.
//
// Важно:
//   - метод не отбрасывает невалидные события;
//   - он сохраняет их, но помечает через счётчики качества.
func (s *Store) AddRaw(raw RawEvent) EventRecord {
	// Нормализуем сырое событие.
	//
	// На этом этапе:
	//   - строка превращается в типизированные поля;
	//   - выявляются ошибки качества;
	//   - формируется список Issues.
	normalized := NormalizeEvent(raw)

	// Добавляем нормализованное событие в хранилище.
	//
	// Даже если событие невалидно, оно будет учтено.
	// Это нужно для честного контроля качества данных.
	s.AddEvent(normalized)

	// Возвращаем нормализованный результат.
	//
	// Это может быть полезно, если инжест хочет вести собственную статистику
	// или немедленно логировать проблемы качества.
	return normalized
}

// IngestFile читает файл форензик-лога и добавляет события в хранилище.
//
// Аргументы:
//   - path: путь к файлу лога.
//
// Возврат:
//   - ошибку открытия, чтения или разбора файла.
//
// Поведение:
//   - файл читается построчно;
//   - каждая строка проходит парсер;
//   - каждое корректно разобранное событие нормализуется;
//   - каждое событие добавляется в кольцевой буфер.
//
// Важно:
//   - это первичный механизм загрузки истории;
//   - для живого потока позже появится отдельный инжест с офсетами.
func (s *Store) IngestFile(path string) error {
	// Используем существующий файловый парсер.
	//
	// Парсер уже умеет:
	//   - читать файл построчно;
	//   - пропускать пустые строки;
	//   - проверять количество полей;
	//   - возвращать ошибки с номером строки.
	//
	// Здесь мы не дублируем эту логику.
	// Мы только подключаем её к хранилищу.
	return ParseFile(path, func(raw RawEvent) error {
		// Для каждой сырой строки:
		//   - нормализуем;
		//   - добавляем в хранилище.
		//
		// Возвращаемое нормализованное событие здесь не используем,
		// потому что текущая задача — просто загрузить данные.
		//
		// Если позже понадобится реакция на ошибки качества прямо в инжесте,
		// можно будет использовать возвращаемое значение.
		s.AddRaw(raw)

		// Возвращаем nil, чтобы продолжить чтение файла.
		//
		// Если вернуть ошибку, ParseFile остановится.
		// Сейчас мы хотим обработать все строки, которые парсер смог разобрать.
		return nil
	})
}

// SnapshotChronological возвращает копию событий в хронологическом порядке.
//
// Возврат:
//   - срез событий от самого старого к самому новому.
//
// Почему возвращаем копию:
//   - вызывающий код не должен держать блокировку хранилища;
//   - веб-панель может спокойно читать снимок;
//   - изменения хранилища не должны ломать уже отданные данные.
//
// Важно:
//   - снимок содержит только события, которые сейчас находятся в кольце;
//   - если старые события были вытеснены, их в снимке уже не будет;
//   - общий объём обработанных событий виден в Counters().
func (s *Store) SnapshotChronological() []EventRecord {
	// Используем блокировку чтения.
	//
	// Несколько читателей могут работать параллельно.
	// Запись в это время будет заблокирована до завершения снимка.
	s.mu.RLock()

	// Гарантируем освобождение блокировки чтения.
	//
	// Даже если снятие снимка займёт время,
	// блокировка должна быть корректно освобождена.
	defer s.mu.RUnlock()

	// Создаём выходной срез заранее известного размера.
	//
	// Это уменьшает количество реаллокаций при заполнении.
	//
	// Если событий нет, вернётся пустой, но не nil-срез.
	// Это удобно для веб-панели и JSON-экспорта.
	out := make([]EventRecord, 0, s.size)

	// Если буфер пуст, сразу возвращаем пустой снимок.
	//
	// Это защищает от отрицательных индексов в расчётах ниже.
	if s.size == 0 {
		return out
	}

	// Вычисляем индекс самого старого события.
	//
	// Логика:
	//   - head указывает на следующую запись;
	//   - значит последнее событие находится перед head;
	//   - самое старое событие находится на size позиций назад от head.
	//
	// Добавляем capacity перед взятием остатка,
	// чтобы избежать отрицательного значения.
	oldest := s.head - s.size + s.capacity
	oldest %= s.capacity

	// Проходим по всем занятым ячейкам кольца.
	//
	// Идём от самого старого события к самому новому.
	// Это естественный порядок для временной ленты.
	for i := 0; i < s.size; i++ {
		// Вычисляем индекс текущей ячейки.
		//
		// Сначала складываем начало и смещение.
		idx := oldest + i

		// Если индекс вышел за пределы буфера, возвращаем его в начало.
		//
		// Так как размер не превышает ёмкость,
		// достаточно одного вычитания.
		// Но для надёжности используем деление по модулю.
		idx %= s.capacity

		// Добавляем событие в снимок.
		//
		// Здесь копируется сама структура события.
		// Строки внутри события не клонируются глубоко,
		// но для аналитического чтения этого достаточно.
		out = append(out, s.ring[idx])
	}

	// Возвращаем готовый хронологический снимок.
	//
	// Он может использоваться для:
	//   - веб-таблицы;
	//   - отладки;
	//   - построения временных линий;
	//   - последующей пакетной агрегации.
	return out
}

// SnapshotNewestFirst возвращает последние события в обратном порядке.
//
// Аргументы:
//   - max: сколько последних событий вернуть.
//
// Поведение:
//   - если max <= 0, возвращаем все доступные события;
//   - если max больше доступного количества, возвращаем все доступные;
//   - события идут от самого нового к самому старому.
//
// Зачем этот метод:
//   - веб-панель обычно показывает последние события первыми;
//   - администратору важнее свежая активность;
//   - не нужно гнать весь буфер, если нужен только хвост.
func (s *Store) SnapshotNewestFirst(max int) []EventRecord {
	// Захватываем блокировку чтения.
	//
	// Снимок должен быть получен на согласованном состоянии кольца.
	// Иначе параллельная запись может исказить выборку.
	s.mu.RLock()

	// Гарантируем освобождение блокировки чтения.
	//
	// Это обязательно даже при раннем выходе.
	defer s.mu.RUnlock()

	// Определяем, сколько событий реально отдадим.
	//
	// Если запрошено неположительное количество,
	// отдаём все доступные события.
	//
	// Если запрошено больше, чем есть в кольце,
	// ограничиваемся фактическим размером.
	limit := max
	if limit <= 0 || limit > s.size {
		limit = s.size
	}

	// Создаём выходной срез заранее известного размера.
	//
	// Это уменьшает реаллокации.
	// Если событий нет, вернётся пустой срез.
	out := make([]EventRecord, 0, limit)

	// Проходим по последним событиям от новых к старым.
	//
	// Последнее событие находится по индексу head-1.
	// Если head равен 0, последнее событие находится в конце кольца.
	for i := 0; i < limit; i++ {
		// Вычисляем индекс нужного события.
		//
		// Начинаем с головы и идём назад.
		//
		// Пример:
		//   - head = 5, i = 0 -> последнее событие в ячейке 4;
		//   - head = 5, i = 1 -> предыдущее событие в ячейке 3.
		idx := s.head - 1 - i

		// Если индекс стал отрицательным, переходим в конец кольца.
		//
		// Это нормальная ситуация для кольцевого буфера.
		//
		// Пример:
		//   - head = 0;
		//   - последнее событие находится в ячейке capacity-1.
		if idx < 0 {
			idx += s.capacity
		}

		// Добавляем событие в снимок.
		//
		// Порядок добавления сознательно обратный:
		// сначала новые, потом старые.
		// Это удобно для веб-таблиц и журнальных лент.
		out = append(out, s.ring[idx])
	}

	// Возвращаем снимок последних событий.
	//
	// Он может быть использован для:
	//   - верхней таблицы веб-панели;
	//   - быстрого просмотра свежих атак;
	//   - диагностики текущей активности.
	return out
}

// Counters возвращает копию служебных счётчиков хранилища.
//
// Возврат:
//   - структура с текущими счётчиками качества и объёма данных.
//
// Зачем:
//   - веб-панель должна показывать не только события, но и качество данных;
//   - администратор должен видеть, сколько битых строк обнаружено;
//   - диагностика должна быть прозрачной.
//
// Важно:
//   - возвращается копия, а не ссылка на внутреннее состояние;
//   - вызывающий код может свободно читать данные без блокировок.
func (s *Store) Counters() StoreCounters {
	// Используем блокировку чтения.
	//
	// Счётчики меняются в AddEvent, поэтому читать их без блокировки нельзя.
	// Иначе можно получить несогласованные значения.
	s.mu.RLock()

	// Гарантируем освобождение блокировки чтения.
	//
	// Это обязательно, даже если тело функции очень короткое.
	defer s.mu.RUnlock()

	// Формируем копию счётчиков.
	//
	// Это защищает внутреннее состояние хранилища.
	// Внешний код получает только снимок.
	return StoreCounters{
		Capacity:       s.capacity,
		Stored:         s.size,
		TotalEvents:    s.totalEvents,
		ValidEvents:    s.validEvents,
		InvalidEvents:  s.invalidEvents,
		IssueCount:     s.issueCount,
		HasEventTime:   s.hasEventTime,
		FirstEventTime: s.firstEventTime,
		LastEventTime:  s.lastEventTime,
	}
}

// Clear очищает хранилище.
//
// Поведение:
//   - кольцевой буфер сбрасывается;
//   - все счётчики обнуляются;
//   - временные границы сбрасываются.
//
// Зачем это может быть нужно:
//   - тесты;
//   - смена источника данных;
//   - принудительная перезагрузка аналитики;
//   - аварийная очистка после повреждения данных.
//
// Важно:
//   - метод не трогает файлы лога;
//   - он очищает только оперативное представление.

// SetIngestPath фиксирует путь к логу для диагностики.
func (s *Store) SetIngestPath(path string) {
	if s == nil {
		return
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	s.ingestPath = path
	s.ingestStarted = true
}

// RecordIngestError сохраняет ошибку парсинга для диагностики.
func (s *Store) RecordIngestError(line string, err error) {
	if s == nil {
		return
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	s.ingestBrokenLines++
	msg := fmt.Sprintf("%s: %s", err.Error(), truncate(line, 80))
	if len(s.ingestLastErrors) >= 5 {
		s.ingestLastErrors = append(s.ingestLastErrors[1:], msg)
	} else {
		s.ingestLastErrors = append(s.ingestLastErrors, msg)
	}
}

// Diagnostics возвращает состояние инжеста для веб-панели.
func (s *Store) Diagnostics() map[string]interface{} {
	if s == nil {
		return map[string]interface{}{"store": "nil"}
	}
	s.mu.RLock()
	defer s.mu.RUnlock()

	// Используем публичный метод Counters() вместо прямого доступа к полям.
	// Это каноничный подход: не лезем во внутренности структуры.
	counters := s.Counters()

	return map[string]interface{}{
		"ingest_path":        s.ingestPath,
		"ingest_started":     s.ingestStarted,
		"ingest_broken":      s.ingestBrokenLines,
		"ingest_last_errors": s.ingestLastErrors,
		"total_events":       counters.TotalEvents,
		"valid_events":       counters.ValidEvents,
		"invalid_events":     counters.InvalidEvents,
	}
}

// truncate обрезает строку до указанной длины.
func truncate(s string, max int) string {
	if len(s) <= max {
		return s
	}
	return s[:max] + "..."
}

func (s *Store) Clear() {
	// Захватываем эксклюзивную блокировку.
	//
	// Очистка меняет всё внутреннее состояние,
	// поэтому параллельные читатели и писатели должны подождать.
	s.mu.Lock()

	// Гарантируем освобождение блокировки.
	//
	// Это обязательно даже при простой операции очистки.
	defer s.mu.Unlock()

	// Создаём новый кольцевой буфер той же ёмкости.
	//
	// Это проще и безопаснее, чем вручную занулять каждую ячейку.
	// Старый буфер будет собран сборщиком мусора.
	s.ring = make([]EventRecord, s.capacity)

	// Сбрасываем индексы кольца.
	//
	// Теперь голова снова в начале,
	// а заполненный размер равен нулю.
	s.head = 0
	s.size = 0

	// Сбрасываем счётчики событий.
	//
	// После очистки история обработки начинается заново.
	s.totalEvents = 0
	s.validEvents = 0
	s.invalidEvents = 0
	s.issueCount = 0

	// Сбрасываем состояние временных границ.
	//
	// Пока нет событий, нет и временной шкалы.
	s.hasEventTime = false
	s.firstEventTime = time.Time{}
	s.lastEventTime = time.Time{}

	// Сбрасываем кольца агрегатной отчётности.
	// При следующем rebuild через RebuildHistory бакеты перестроятся
	// автоматически — тот же AddEvent вызовет GlobalRollup.Ingest.
	if GlobalRollup != nil {
		GlobalRollup.Reset()
	}

}
