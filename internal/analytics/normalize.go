// addIssue добавляет проблему качества данных в список.
//
// Это внутренний метод, чтобы не повторять один и тот же код
// в каждом месте проверки полей.
func (rec *EventRecord) addIssue(field int, name string, value string, message string) {
	// Создаём структуру проблемы.
	//
	// Все поля обязательны для диагностики:
	//   - индекс поля;
	//   - имя поля;
	//   - сырое значение;
	//   - причина.
	issue := FieldIssue{
		Field:   field,
		Name:    name,
		Value:   value,
		Message: message,
	}

	// Добавляем проблему в список.
	//
	// Один и тот же событие может иметь несколько проблем одновременно.
	// Например:
	//   - битое время;
	//   - битый порт;
	//   - пустой токен.
	rec.Issues = append(rec.Issues, issue)
}

// uintField разбирает беззнаковое целое поле и при ошибке фиксирует проблему.
//
// Аргументы:
//   - field: индекс поля;
//   - name: человекочитаемое имя поля;
//   - value: сырое строковое значение;
//   - bitSize: размер числа в битах: 8, 16, 32 или 64.
//
// Возврат:
//   - значение и true, если разбор успешен;
//   - 0 и false, если разбор не удался.
//
// Почему используем этот метод:
//   - не дублируем проверку ошибок;
//   - все числовые проблемы фиксируются одинаково;
//   - код нормализации остаётся читаемым.
func (rec *EventRecord) uintField(field int, name string, value string, bitSize int) (uint64, bool) {
	// Пытаемся разобрать строку как беззнаковое целое.
	//
	// Основание 10.
	// Если позже появятся шестнадцатеричные поля, добавим отдельный парсер.
	parsedValue, err := parseUint(value, bitSize)
	if err != nil {
		// Если разбор не удался, фиксируем проблему.
		//
		// В issue сохраняем:
		//   - какое поле;
		//   - какое сырое значение;
		//   - причину ошибки.
		rec.addIssue(
			field,
			name,
			value,
			err.Error(),
		)

		// Возвращаем признак неудачи.
		//
		// Вызывающий код при этом не прерывает всю нормализацию.
		// Остальные поля продолжают обрабатываться.
		return 0, false
	}

	// Разбор успешен.
	//
	// Возвращаем значение и признак успеха.
	// Приведение к конкретному типу делает вызывающий код,
	// потому что разные поля имеют разные типы:
	//   - uint8;
	//   - uint16;
	//   - uint32;
	//   - uint64.
	return parsedValue, true
}

// parseUint разбирает строку как беззнаковое целое число.
//
// Аргументы:
//   - value: сырое строковое значение;
//   - bitSize: размер числа в битах: 8, 16, 32 или 64.
//
// Возврат:
//   - число и ошибку, если значение не является корректным.
//
// Почему используем strconv.ParseUint:
//   - оно строго проверяет формат;
//   - оно контролирует переполнение по заданному битовому размеру;
//   - оно не принимает отрицательные значения.
func parseUint(value string, bitSize int) (uint64, error) {
	// Обрезаем пробелы по краям.
	//
	// Это защищает от значений вида:
	//   - " 14480"
	//   - "14480 "
	//   - " 14480 "
	trimmed := strings.TrimSpace(value)

	// Пустое значение недопустимо.
	//
	// Если поле действительно может быть пустым,
	// это должно решаться на уровне контракта,
	// а не молчаливым превращением в ноль.
	if trimmed == "" {
		return 0, fmt.Errorf("empty value")
	}

	// Пытаемся разобрать число.
	//
	// Используем десятичное представление.
	// Если значение не проходит, возвращаем ошибку с контекстом.
	parsed, err := strconv.ParseUint(trimmed, 10, bitSize)
	if err != nil {
		// Оборачиваем ошибку, чтобы было понятно,
		// что проблема именно в числовом поле.
		//
		// Оригинальная ошибка сохраняется через %w.
		// Это полезно для будущей диагностики.
		return 0, fmt.Errorf("invalid unsigned integer: %w", err)
	}

	// Возвращаем успешно разобранное число.
	//
	// Оно уже проверено на:
	//   - формат;
	//   - отсутствие знака;
	//   - переполнение для заданного битового размера.
	return parsed, nil
}

// parseHoldSeconds разбирает значения удержания вида:
//
//	"17"
//	"17 sec"
//	"17 s"
//	"17sec"
//
// Возвращает значение в секундах.
//
// Почему отдельный парсер:
//   - поля плана и факта могут содержать текстовый суффикс;
//   - мы должны привести их к единой числовой форме;
//   - единица измерения здесь критична для дельты план/факт.
func parseHoldSeconds(value string) (uint64, error) {
	// Обрезаем пробелы по краям.
	//
	// Это защищает от лишних пробелов в логе.
	trimmed := strings.TrimSpace(value)

	// Пустое значение недопустимо.
	//
	// План и факт являются ключевыми поведенческими метриками,
	// поэтому пустота должна быть видна как проблема качества данных.
	if trimmed == "" {
		return 0, fmt.Errorf("empty hold value")
	}

	// Разбиваем значение по пробельным последовательностям.
	//
	// Например:
	//   - "17 sec" -> ["17", "sec"]
	//   - "17"     -> ["17"]
	//   - "17 s"   -> ["17", "s"]
	//
	// Берём первый элемент.
	// В текущем формате число должно быть первым.
	parts := strings.Fields(trimmed)

	// Получаем первый токен.
	//
	// Это может быть:
	//   - "17"
	//   - "17sec"
	//   - "17s"
	token := parts[0]

	// Переводим токен в нижний регистр.
	//
	// Это нужно, чтобы суффиксы вроде:
	//   - "SEC"
	//   - "Sec"
	//   - "S"
	// обрабатывались одинаково.
	token = strings.ToLower(token)

	// Отрезаем суффикс "sec".
	//
	// Например:
	//   - "17sec" -> "17"
	//   - "17"    -> "17"
	//
	// Если суффикса нет, значение не изменится.
	token = strings.TrimSuffix(token, "sec")

	// Отрезаем суффикс "s".
	//
	// Например:
	//   - "17s" -> "17"
	//   - "17"  -> "17"
	//
	// Если суффикса нет, значение не изменится.
	token = strings.TrimSuffix(token, "s")

	// Повторно обрезаем возможные пробелы.
	//
	// Обычно после обрезки суффиксов пробелов не остаётся,
	// но защита лишней не будет.
	token = strings.TrimSpace(token)

	// Если после удаления суффиксов числовая часть исчезла,
	// значение считается битым.
	//
	// Пример битого значения:
	//   - "sec"
	//   - "s"
	//   - "  sec"
	if token == "" {
		return 0, fmt.Errorf("missing numeric hold value")
	}

	// Разбираем числовую часть как 64-битное беззнаковое целое.
	//
	// Секунды удержания не должны быть отрицательными.
	// Отрицательное значение в логе уже само по себе проблема.
	parsed, err := strconv.ParseUint(token, 10, 64)
	if err != nil {
		// Возвращаем ошибку с понятным контекстом.
		//
		// Это позволяет в веб-панели показать,
		// что именно поле удержания имеет неверный формат.
		return 0, fmt.Errorf("invalid hold value: %w", err)
	}

	// Возвращаем значение в секундах.
	//
	// На этом этапе мы сознательно не поддерживаем миллисекунды.
	// Если реальный лог покажет другой формат, добавим поддержку отдельно.
	return parsed, nil
}

// normalizeBehavior приводит строку поведения к канонической форме.
//
// Возврат:
//   - исходное сырое значение;
//   - нормализованное значение;
//   - признак успеха.
//
// Почему делаем так:
//   - исходное значение нужно для аудита;
//   - нормализованное значение нужно для агрегации;
//   - признак успеха нужен для контроля качества.
func normalizeBehavior(value string) (string, string, bool) {
	// Сохраняем исходное значение, обрезав крайние пробелы.
	//
	// Это значение будет сохранено в EventRecord.BehaviorRaw.
	raw := strings.TrimSpace(value)

	// Переводим значение в верхний регистр.
	//
	// Это позволяет не зависеть от регистра:
	//   - "PASSIVE_SCANNER"
	//   - "passive_scanner"
	//   - "Passive_Scanner"
	upper := strings.ToUpper(raw)

	// Проверяем известные варианты.
	//
	// Используем Contains, а не точное совпадение,
	// чтобы поддерживать варианты вроде:
	//   - "AGGRESSIVE_SCANNER"
	//   - "PASSIVE_SCANNER"
	//   - будущие расширения с тем же корнем.
	switch {
	case strings.Contains(upper, "AGGRESSIVE"):
		// Агрессивное поведение.
		//
		// Возвращаем короткую каноническую форму.
		//
		// Короткая форма удобнее для:
		//   - веб-таблиц;
		//   - графиков;
		//   - внутренних сравнений.
		return raw, "AGGRESSIVE", true

	case strings.Contains(upper, "PASSIVE"):
		// Пассивное поведение.
		//
		// Возвращаем короткую каноническую форму.
		//
		// Короткая форма удобнее для:
		//   - веб-таблиц;
		//   - графиков;
		//   - внутренних сравнений.
		return raw, "PASSIVE", true

	default:
		// Поведение не распознано.
		//
		// Возвращаем:
		//   - исходное значение;
		//   - пустую нормализованную форму;
		//   - признак неудачи.
		//
		// Это позволит веб-панели показать реальный сырой маркер.
		return raw, "", false
	}
}

// normalizeCloseReason приводит причину закрытия к канонической форме.
//
// Возврат:
//   - нормализованное значение в верхнем регистре;
//   - признак успеха.
//
// Почему важно:
//   - причины закрытия влияют на фазовый анализ;
//   - причины закрытия влияют на психологию удержания;
//   - разные регистры не должны ломать статистику.
func normalizeCloseReason(value string) (string, bool) {
	// Обрезаем пробелы и переводим в верхний регистр.
	//
	// Это приводит значения к единому виду:
	//   - "fin" -> "FIN"
	//   - " RST " -> "RST"
	//   - "Timeout" -> "TIMEOUT"
	normalized := strings.ToUpper(strings.TrimSpace(value))

	// Проверяем известные причины закрытия.
	//
	// Список соответствует текущей спецификации:
	//   - FIN;
	//   - RST;
	//   - TIMEOUT;
	//   - OUR_CLOSE.
	switch normalized {
	case "FIN":
		// Закрытие по FIN.
		//
		// Обычно означает корректное завершение соединения.
		// Для бота это может быть признаком внутреннего таймаута.
		return normalized, true

	case "RST":
		// Закрытие по RST.
		//
		// Обычно означает грубый сброс соединения.
		// Может указывать на панику, переполнение или принудительный обрыв.
		return normalized, true

	case "TIMEOUT":
		// Закрытие по таймауту.
		//
		// Обычно означает, что бот остался висеть в капкане
		// до исхода нашего удержания.
		return normalized, true

	case "OUR_CLOSE":
		// Закрытие нашей стороной.
		//
		// Важно:
		// это действие комплекса, а не обязательно поведение бота.
		//
		// Позже обязательно добавим атрибуцию закрытия,
		// чтобы не приписывать это поведение атакующему.
		return normalized, true

	default:
		// Неизвестная причина закрытия.
		//
		// Возвращаем нормализованное значение, чтобы его можно было увидеть,
		// но помечаем как нераспознанное.
		//
		// Это честно:
		//   - данные не потеряны;
		//   - но интерпретация невозможна без расширения словаря.
		return normalized, false
	}
}

// startTimeLayouts содержит поддерживаемые форматы времени.
//
// Порядок важен:
//   - сначала более строгие форматы с таймзоной;
//   - затем форматы без таймзоны.
//
// Если реальный лог покажет новый формат,
// его нужно добавить сюда, а не править парсер вручную в нескольких местах.
var startTimeLayouts = []string{
	// RFC3339 с наносекундами и таймзоной.
	//
	// Пример:
	//   2026-10-17T17:39:15.123456789Z
	time.RFC3339Nano,

	// RFC3339 без дробной части, но с таймзоной.
	//
	// Пример:
	//   2026-10-17T17:39:15Z
	time.RFC3339,

	// ISO-подобный формат с разделителем T и наносекундами,
	// но без таймзоны.
	//
	// Пример:
	//   2026-10-17T17:39:15.123456789
	"2006-01-02T15:04:05.999999999",

	// ISO-подобный формат с разделителем T,
	// без дробной части и без таймзоны.
	//
	// Пример:
	//   2026-10-17T17:39:15
	"2006-01-02T15:04:05",

	// Формат с пробелом и дробной частью секунды,
	// без таймзоны.
	//
	// Пример:
	//   2026-10-17 17:39:15.123456789
	"2006-01-02 15:04:05.999999999",

	// Формат с пробелом, без дробной части и без таймзоны.
	//
	// Пример:
	//   2026-10-17 17:39:15
	//
	// Это основной ожидаемый формат текущего лога.
	"2006-01-02 15:04:05",
}

// parseStartTime разбирает строку времени.
//
// Возврат:
//   - время в UTC;
//   - признак, что время было без явной таймзоны и принято как UTC;
//   - ошибку разбора.
//
// Почему возвращаем время в UTC:
//   - все агрегаты должны быть в одной системе координат;
//   - часовые срезы не должны зависеть от локальной таймзоны сервера;
//   - веб-панель сможет отображать время в нужном формате позже.
func parseStartTime(value string) (time.Time, bool, error) {
	// Обрезаем пробелы по краям.
	//
	// Это защищает от случайных пробелов в начале или конце поля.
	trimmed := strings.TrimSpace(value)

	// Пустое время недопустимо.
	//
	// Без времени событие нельзя привязать к часовой статистике.
	if trimmed == "" {
		return time.Time{}, false, fmt.Errorf("empty time")
	}

	// Проходим по всем поддерживаемым форматам.
	//
	// Если один формат не подошёл, пробуем следующий.
	// Это позволяет поддерживать несколько вариантов написания времени.
	for _, layout := range startTimeLayouts {
		// Пытаемся разобрать время по текущему формату.
		//
		// Если формат не подошёл, продолжаем цикл.
		//
		// ВАЖНО (v8.6.2, калибровка Алгоритма 2):
		// Для форматов БЕЗ явной таймзоны интерпретируем строку как ЛОКАЛЬНОЕ
		// время сервера. Это соответствует тому, как tarpit_logger пишет время:
		//   entry.Timestamp.Format("2006-01-02 15:04:05")
		// даёт локальное представление (MSK/CET/whatever), а НЕ UTC.
		//
		// Раньше мы парсили такие строки через time.Parse, который по умолчанию
		// считает беззонные строки UTC. Это давало систематическую ошибку:
		// дрейф в профиле всегда показывал -(часовой пояс сервера).
		// Например, для Europe/Moscow: -10800000 мс = ровно -3 часа.
		//
		// Решение: time.ParseInLocation(layout, trimmed, time.Local)
		// для беззонных форматов. Теперь StartTime корректно отражает
		// абсолютное время события, и дрейф ≈ 0 мс (норма).
		var parsed time.Time
		var err error

		// Формат с таймзоной содержит Z07:00 или -07:00 в layout (RFC3339/RFC3339Nano).
		if strings.Contains(layout, "Z07:00") || strings.Contains(layout, "-07:00") {
			// time.Parse корректно учтёт смещение из самой строки.
			parsed, err = time.Parse(layout, trimmed)
		} else {
			// Формат БЕЗ таймзоны: интерпретируем как локальное время сервера.
			parsed, err = time.ParseInLocation(layout, trimmed, time.Local)
		}
		if err != nil {
			continue
		}

		// Время успешно разобрано.
		//
		// assumedUTC теперь означает "строка не содержала явной таймзоны"
		// (т.е. мы её домыслили через time.Local).
		assumedUTC := !strings.Contains(trimmed, "Z") &&
			!strings.Contains(trimmed, "+") &&
			!strings.Contains(trimmed, "-") || strings.Count(trimmed, "-") == 2

		// Возвращаем время в UTC для единообразия всех агрегатов.
		//
		// Даже если исходное время было локальным или со смещением,
		// мы храним его как UTC. Все часовые срезы работают в UTC.
		return parsed.UTC(), assumedUTC, nil
	}

	// Ни один формат не подошёл.
	//
	// Возвращаем ошибку.
	//
	// В будущем можно добавить более подробную диагностику,
	// но сейчас важно просто не пропустить битое время.
	return time.Time{}, false, fmt.Errorf("unsupported time format")
}
