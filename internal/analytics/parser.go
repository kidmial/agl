// КОМПОНЕНТ: ПАРСЕР СЫРЫХ ФОРЕНЗИК-ЛОГОВ
// РОЛЬ: Разбор строк tarpit_report.log в RawEvent.
// ПРИНЦИП: Парсер только читает и проверяет структуру.
//
//	Он не считает статистику и не делает выводов.
//
