package analytics

import (
	"bufio"
	"errors"
	"fmt"
	"io"
	"os"
	"strings"
)

// ParseLine разбирает одну строку форензик-лога.
//
// Аргументы:
//   - line: сама строка без завершающего перевода строки;
//   - lineNum: номер строки в файле;
//   - source: источник, например путь к файлу.
//
// Возврат:
//   - RawEvent, если строка корректна;
//   - ошибку, если строка пустая или имеет неверное число полей.
func ParseLine(line string, lineNum int, source string) (RawEvent, error) {
	// Сразу проверяем, что строка не является пустой или пробельной.
	// Пустые строки допускаются в логах после ротации или ручных правок.
	// Их нужно просто пропустить, не ломая весь парсинг.
	if strings.TrimSpace(line) == "" {
		return RawEvent{}, ErrEmptyLine
	}

	// Разделяем строку по символу табуляции.
	// Текущий форензик-лог использует таб-разделённый формат.
	//
	// Почему не используем пробелы:
	//   - некоторые значения могут содержать пробелы;
	//   - таб даёт более предсказуемую структуру.
	parts := strings.Split(line, "\t")

	// Проверяем, что получили ровно 30 полей.
	// Если полей меньше или больше, строка считается битой.
	//
	// Почему это важно:
	//   - аналитика не должна молча работать на повреждённых данных;
	//   - каждая битая строка должна быть видна как проблема качества данных.
	if len(parts) != FieldCount {
		return RawEvent{}, fmt.Errorf(
			"%w: expected %d, got %d",
			ErrFieldCount,
			FieldCount,
			len(parts),
		)
	}

	// Создаём сырое событие.
	// Пока заполняем только служебные поля.
	var event RawEvent

	// Сохраняем источник.
	// Это нужно для диагностики и аудита.
	event.Source = source

	// Сохраняем номер строки.
	// Это нужно для быстрого поиска проблемной записи в файле.
	event.Line = lineNum

	// Сохраняем исходную строку.
	// Это форензический оригинал.
	// Мы не должны терять его даже после нормализации.
	event.Raw = line

	// Проходим по всем 30 полям.
	//
	// Почему делаем это в цикле:
	//   - размер контракта фиксирован;
	//   - так мы не зависим от случайных ошибок с индексами;
	//   - каждое поле дополнительно очищается от крайних пробелов.
	for i := 0; i < FieldCount; i++ {
		// Обрезаем пробелы и переводы каретки по краям.
		//
		// Зачем:
		//   - значения могли быть записаны с лишними пробелами;
		//   - дальше нормализатору будет проще приводить их к числам.
		//
		// Важно:
		//   - внутренние пробелы сохраняются;
		//   - например "17 sec" останется "17 sec", а не "17sec".
		event.Fields[i] = strings.TrimSpace(parts[i])
	}

	// Возвращаем успешно разобранное сырое событие.
	// На этом этапе парсер не пытается понять смысл значений.
	return event, nil
}

// ParseReader читает поток строк и передаёт каждое корректное событие в emit.
//
// Аргументы:
//   - r: источник данных, например файл или буфер;
//   - source: имя источника для аудита;
//   - emit: callback, который вызывается для каждой корректной строки.
//
// Возврат:
//   - ошибку чтения, разбора или ошибку, возвращённую из emit.
//
// Почему используем callback:
//   - лог может быть большим;
//   - не хотим держать все события в памяти одновременно;
//   - вызывающий код сам решит, что делать: копить, агрегировать, валидировать.
func ParseReader(r io.Reader, source string, emit func(RawEvent) error) error {
	// Создаём потоковый читатель строк.
	//
	// Почему bufio.Scanner:
	//   - он эффективно читает файл построчно;
	//   - не требует загружать весь файл в память.
	scanner := bufio.NewScanner(r)

	// Задаём начальный буфер.
	//
	// Зачем:
	//   - строки форензика обычно небольшие;
	//   - но мы закладываем запас на длинные токены и страны.
	buffer := make([]byte, 64*1024)

	// Устанавливаем буфер сканера.
	//
	// Второй аргумент задаёт жёсткий максимум.
	// 1 МБ достаточно для текущей строки из 30 полей.
	//
	// Если строка окажется длиннее, сканер вернёт ошибку.
	// Это лучше, чем молча получить обрезанные данные.
	scanner.Buffer(buffer, 1024*1024)

	// Счётчик строк.
	//
	// Важно:
	//   - нумерация начинается с 1, как принято в текстовых файлах;
	//   - это упрощает поиск битой строки вручную.
	lineNum := 0

	// Читаем файл строка за строкой.
	//
	// Цикл продолжается, пока сканер успешно читает следующую строку.
	// Ошибка чтения будет обработана после цикла.
	for scanner.Scan() {
		// Увеличиваем номер строки.
		//
		// Делаем это до парсинга, чтобы ошибка содержала корректный номер.
		lineNum++

		// Получаем текст текущей строки.
		//
		// Важно:
		//   - перевод строки уже удалён;
		//   - сырое событие сохранит именно этот текст.
		line := scanner.Text()

		// Пытаемся разобрать строку.
		//
		// Здесь мы ещё не нормализуем числа и время.
		// Только проверяем структуру.
		event, err := ParseLine(line, lineNum, source)
		if err != nil {
			// Если строка пустая, пропускаем её.
			//
			// Это нормальная ситуация.
			// Пустые строки не должны останавливать парсинг всего файла.
			if errors.Is(err, ErrEmptyLine) {
				continue
			}

			// Если строка битая, возвращаем ошибку.
			//
			// Почему не пропускаем молча:
			//   - форензика требует видимости повреждений;
			//   - позже мы сможем заменить это на политику пропуска,
			//     но сейчас безопаснее остановиться.
			return fmt.Errorf("parse %s:%d: %w", source, lineNum, err)
		}

		// Если вызывающий код не задал обработчик, просто продолжаем.
		//
		// Это позволяет использовать ParseReader как инструмент валидации:
		//   - пройти весь файл;
		//   - проверить структуру;
		//   - ничего не сохранить.
		if emit != nil {
			// Передаём событие вызывающему коду.
			//
			// Если emit вернул ошибку, останавливаем парсинг.
			// Это нужно, чтобы потребитель мог управлять остановкой:
			//   - переполнение памяти;
			//   - ошибка базы;
			//   - запрос на отмену.
			if err := emit(event); err != nil {
				return err
			}
		}
	}

	// Проверяем, не было ли ошибки чтения.
	//
	// Важно:
	//   - после завершения цикла нужно обязательно проверить scanner.Err();
	//   - иначе можно потерять ошибку обрыва файла или превышения буфера.
	if err := scanner.Err(); err != nil {
		return fmt.Errorf("scan %s: %w", source, err)
	}

	// Весь поток успешно обработан.
	//
	// Если были пустые строки, они уже пропущены.
	// Если были битые строки, мы остановились на первой из них.
	return nil
}

// ParseFile открывает файл и передаёт его в ParseReader.
//
// Аргументы:
//   - path: путь к файлу форензик-лога;
//   - emit: обработчик событий.
//
// Возврат:
//   - ошибку открытия файла;
//   - ошибку чтения или парсинга.
//
// Это основная точка входа для первичного полного разбора логов.
func ParseFile(path string, emit func(RawEvent) error) error {
	// Открываем файл только для чтения.
	//
	// Почему используем os.Open, а не os.OpenFile с записью:
	//   - парсер не должен менять форензик-лог;
	//   - оригинальные логи остаются неизменяемыми.
	file, err := os.Open(path)
	if err != nil {
		// Если файл не открыт, возвращаем ошибку с контекстом.
		//
		// Причины могут быть:
		//   - файл отсутствует;
		//   - нет прав;
		//   - путь битый.
		return fmt.Errorf("open %s: %w", path, err)
	}

	// Гарантируем закрытие файла после завершения чтения.
	//
	// Важно:
	//   - файл должен быть закрыт даже при ошибке парсинга;
	//   - отложенное закрытие защищает от утечки файловых дескрипторов.
	defer file.Close()

	// Передаём открытый файл в потоковый парсер.
	//
	// В качестве источника указываем путь к файлу.
	// Это сохранится в каждом событии.
	return ParseReader(file, path, emit)
}
