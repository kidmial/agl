package analytics

import (
	"errors"
)

// FieldCount задаёт ожидаемое количество полей в одной строке
// форензик-отчёта tarpit_report.log.
//
// Почему именно 30:
//   - это полный состав метрик, зафиксированный в доктрине проекта;
//   - парсер обязан проверять целостность строки до любой обработки.
const FieldCount = 30

// Индексы полей в сырой строке лога.
//
// Порядок строго соответствует текущему формату:
// время, TarpitID, IP, план, факт, поведение, страна, порт, токен,
// затем TCP-метрики и IAT-метрики.
//
// Эти константы нужны, чтобы дальше не использовать магические числа.
const (
	// Эшелон 1. Идентификация и статус.
	FieldStartTime   = iota // 0. Время начала сессии.
	FieldTarpitID           // 1. Идентификатор капкана.
	FieldIP                 // 2. IP-адрес атакующего.
	FieldPlannedHold        // 3. Запланированный джиттер/удержание.
	FieldActualHold         // 4. Фактическое удержание.
	FieldBehavior           // 5. Поведение: PASSIVE/AGGRESSIVE.
	FieldCountry            // 6. Страна по GeoIP.
	FieldSourcePort         // 7. Исходный порт атакующего.
	FieldToken              // 8. Форензик-токен.

	// Эшелон 2. Спецификация TCP/IP.
	FieldMSS          // 9. MSS.
	FieldSndCwnd      // 10. Окно отправки.
	FieldRcvSpace     // 11. Буфер приёма.
	FieldRTT          // 12. RTT.
	FieldTotalRetrans // 13. Накопленные ретрансмиты.
	FieldState        // 14. Состояние сокета.
	FieldRetransmits  // 15. Текущие неподтверждённые ретрансмиты.
	FieldProbes       // 16. Зонды.
	FieldSndWscale    // 17. Масштаб окна отправки.
	FieldRcvWscale    // 18. Масштаб окна приёма.
	FieldCloseReason  // 19. Причина закрытия.

	// Эшелон 3. Поведение и L7 / IAT.
	FieldIATCount       // 20. Количество интервалов между чтениями.
	FieldIATSumMs       // 21. Сумма интервалов.
	FieldIATMinMs       // 22. Минимальный интервал.
	FieldIATMaxMs       // 23. Максимальный интервал.
	FieldIATSumSqMs     // 24. Сумма квадратов интервалов.
	FieldReadTiny       // 25. Чтения 0–64 байта.
	FieldReadSmall      // 26. Чтения 65–256 байт.
	FieldReadMedium     // 27. Чтения 257–1024 байт.
	FieldReadLarge      // 28. Чтения свыше 1024 байт.
	FieldWriteLatencyMs // 29. Задержка записи.
)

// Ошибки парсера.
//
// Выносим их отдельно, чтобы вызывающий код мог различать:
//   - пустую строку, которую можно пропустить;
//   - реально битую строку, которую нужно учитывать как инцидент качества данных.
var (
	// ErrEmptyLine означает, что строка пустая.
	// Это не ошибка данных, а нормальный случай для пропуска.
	ErrEmptyLine = errors.New("analytics: empty line")

	// ErrFieldCount означает, что строка не содержит ровно 30 полей.
	// Это уже нарушение целостности форензик-записи.
	ErrFieldCount = errors.New("analytics: invalid field count")
)

// RawEvent описывает одну сырую строку лога после первичного разбора.
//
// Важно:
//   - здесь все поля остаются строками;
//   - здесь ещё нет чисел, дат и интерпретаций;
//   - это осознанный выбор, чтобы парсер не зависел от будущих решений
//     по типам, единицам и правилам нормализации.
type RawEvent struct {
	// Source хранит источник события.
	// Обычно это путь к файлу лога.
	// Нужно для аудита и диагностики.
	Source string

	// Line хранит номер строки в файле.
	// Нужно для быстрого поиска битой записи.
	Line int

	// Raw хранит исходную строку.
	// Это форензическая копия.
	// Даже после нормализации мы должны иметь возможность вернуться к оригиналу.
	Raw string

	// Fields содержит 30 полей строки.
	// Массив фиксированного размера защищает от случайного расширения
	// или обрезания контракта.
	Fields [FieldCount]string
}

// Field безопасно возвращает значение поля по индексу.
//
// Зачем:
//   - вне пакета индексы могут использоваться через константы;
//   - при ошибочном индексе лучше вернуть пустую строку,
//     чем допустить panic.
func (e RawEvent) Field(index int) string {
	// Проверяем границу слева.
	// Отрицательный индекс недопустим.
	if index < 0 {
		return ""
	}

	// Проверяем границу справа.
	// Индекс должен быть меньше количества полей.
	if index >= FieldCount {
		return ""
	}

	// Возвращаем значение поля.
	// Здесь значение ещё сырое, но уже обрезанное по краям.
	return e.Fields[index]
}
