// GetActiveTrappedBotsCount осуществляет резервное сканирование ОЗУ-таблиц
// ядра Linux для подсчёта активных ботов. Используется если `/dev/shm/`
// недоступен.
//
// АЛГОРИТМ:
//  1. Открыть `/proc/net/tcp` и `/proc/net/tcp6` (таблицы соединений ядра)
//  2. Парсить каждую строку: извлекать локальный порт и состояние сокета
//  3. Искать порт ловушки (порт 22) в состоянии `ESTABLISHED` (код `01`)
//  4. Считать количество совпадений
//
// ЗАДЕРЖКА: ~1 миллисекунда (чтение двух файлов из `/proc`).
// Это приемлемо для резервного механизма, но НЕ для основного.
//
// ОГРАНИЧЕНИЕ ТЕКУЩЕЙ ВЕРСИИ:
// Сканирует только порт 22 (`config.C.StandardSshPort`).
// В будущем нужно расширить на все активные порты из инвентаря.
//
// ОБНОВЛЕНО В v8.0.1: Восстановлено из закомментированного кода.
// Добавлен комментарий об ограничении для будущей доработки.
func GetActiveTrappedBotsCount() int {
	// Исследовательский пул виртуальных таблиц сетевого стека Linux.
	// `/proc/net/tcp` — IPv4 соединения
	// `/proc/net/tcp6` — IPv6 соединения (может отсутствовать если IPv6 отключен)
	// ОБНОВЛЕНО В v8.0.1.
	targets := []string{"/proc/net/tcp", "/proc/net/tcp6"}
	count := 0

	// Вычисляем динамический HEX-код порта ловушки.
	// В `/proc/net/tcp` порты записаны в шестнадцатеричном формате (4 символа).
	// Порт 22 = `0016` в HEX.
	// ОБНОВЛЕНО В v8.0.1.
	// v8.0.3 (Аудит №9): множество HEX-портов ВСЕХ RUNNING-ловушек,
	// а не только базового порта 22.
	targetHex := map[string]bool{fmt.Sprintf("%04X", config.C.StandardSshPort): true}
	if inv, err := sys.LoadTarpitInventory(sys.TarpitInventoryPath); err == nil {
		for _, trap := range inv.Traps {
			if trap.State == sys.StateRunning {
				targetHex[fmt.Sprintf("%04X", trap.Port)] = true
			}
		}
	}

	for _, path := range targets {
		file, err := os.Open(path)
		if err != nil {
			// Если `/proc/net/tcp6` недоступен (IPv6 отключен), пропускаем.
			// Это нормальная ситуация на серверах без IPv6.
			// ОБНОВЛЕНО В v8.0.1.
			continue
		}

		scanner := bufio.NewScanner(file)

		// Пропускаем заголовок таблицы ядра (первая строка).
		// ОБНОВЛЕНО В v8.0.1.
		if scanner.Scan() {
			_ = scanner.Text() // Пропуск заголовка
		}

		for scanner.Scan() {
			fields := strings.Fields(scanner.Text())
			if len(fields) < 4 {
				continue
			}

			// fields[1] — локальный адрес и порт в формате HEX.
			// Пример для IPv4: `00000000:0016` (порт 22)
			// Пример для IPv6: `0000000000000000FFFF00000100007F:0016`
			// ОБНОВЛЕНО В v8.0.1.
			localAddr := fields[1]
			parts := strings.Split(localAddr, ":")
			if len(parts) < 2 {
				continue
			}
			localPortHex := parts[1]

			// fields[3] — состояние сокета (код из 2 цифр).
			// `01` = `ESTABLISHED` (соединение установлено).
			// Нас интересуют только установленные соединения (боты в капкане).
			// ОБНОВЛЕНО В v8.0.1.
			connState := fields[3]

			// Ищем порт ловушки в состоянии `ESTABLISHED`.
			// Если порт совпадает и соединение установлено — бот в капкане.
			// ОБНОВЛЕНО В v8.0.1.
			if targetHex[strings.ToUpper(localPortHex)] && connState == "01" {
				count++
			}
		}
		file.Close()
	}
	return count
}
