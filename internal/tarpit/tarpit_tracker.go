// InitShmSlave подключает графический пульт (TUI) к существующему файлу
// общей памяти, созданному демоном. Вызывается из `main.go` при старте TUI.
//
// АЛГОРИТМ:
//  1. Открыть существующий файл `/dev/shm/amberguard.counter` для чтения
//  2. Выполнить `syscall.Mmap` с `PROT_READ` для маппирования в память процесса
//  3. Привести `[]byte` к `*int32` через `unsafe.Pointer`
//
// ВАЖНО: Если файл не существует (демон ещё не запущен), функция молча выходит.
// `GetLiveBotsShmCount()` использует фолбэк на резервное сканирование.
//
// ОБНОВЛЕНО В v8.0.1: Восстановлено из закомментированного кода.
// Вызывается из `main.go` перед запуском `tui.StartTarpitControlPanel()`.
func InitShmSlave() {
	// Открываем файл в режиме только для чтения.
	// Если файл не существует (демон не запущен), выходим с ошибкой.
	// Фолбэк будет обработан в `GetLiveBotsShmCount()`.
	// ОБНОВЛЕНО В v8.0.1.
	file, err := os.OpenFile(config.FileShm, os.O_RDONLY, 0666)
	if err != nil {
		return
	}
	defer file.Close()

	// Маппируем файл в память процесса с разрешением только для чтения.
	// `PROT_READ` достаточно, так как `atomic.LoadInt32` только читает, не пишет.
	// `MAP_SHARED` гарантирует, что мы видим актуальные данные, записанные демоном.
	// ОБНОВЛЕНО В v8.0.1.
	data, err := syscall.Mmap(int(file.Fd()), 0, 4,
		syscall.PROT_READ,
		syscall.MAP_SHARED)
	if err != nil {
		return
	}

	// Сохраняем маппированный байтовый срез и приводим к `*int32`.
	// ОБНОВЛЕНО В v8.0.1.
	shmData = data
	shmCounter = (*int32)(unsafe.Pointer(&shmData[0]))
}

