// IncrementLiveBots атомарно увеличивает счётчик ботов на 1.
// Вызывается из `handleIncomingBot` и `handleIncomingBotCustom` в момент
// ПЕРВОГО КАСАНИЯ ботом сокета ловушки.
//
// ЗАДЕРЖКА: 0 наносекунд (одна атомарная инструкция процессора).
// Нет вызовов `syscall`, нет дискового ввода-вывода, нет блокировок.
//
// ОБНОВЛЕНО В v8.0.1: Использует маппированную память `/dev/shm/`.
// Если маппинг недоступен, использует атомарную переменную как фолбэк.
func IncrementLiveBots() {
	if shmCounter != nil {
		// Основной путь: атомарный инкремент в маппированной памяти `/dev/shm/`
		// ОБНОВЛЕНО В v8.0.1.
		atomic.AddInt32(shmCounter, 1)
		return
	}
	// Фолбэк: если маппинг не инициализирован, используем локальную переменную.
	// Это покрывает случай, когда демон и воркеры в одном процессе.
	// ОБНОВЛЕНО В v8.0.1.
	atomic.AddInt32(&internalFallbackCounter, 1)
}

// DecrementLiveBots атомарно уменьшает счётчик ботов на 1.
// Вызывается из `handleIncomingBot` и `handleIncomingBotCustom` через `defer`
// в момент ОСВОБОЖДЕНИЯ сокета (завершение цикла удержания).
//
// ЗАЩИТА ОТ ОТРИЦАТЕЛЬНОГО СЧЁТЧИКА:
// Проверяем, что счётчик > 0 перед декрементом.
// Это защищает от переполнения при некорректном порядке вызовов.
//
// ОБНОВЛЕНО В v8.0.1: Использует маппированную память `/dev/shm/`.
func DecrementLiveBots() {
	if shmCounter != nil {
		// Основной путь: атомарный декремент в маппированной памяти.
		// Защита от отрицательного значения.
		// ОБНОВЛЕНО В v8.0.1.
		if atomic.LoadInt32(shmCounter) > 0 {
			atomic.AddInt32(shmCounter, -1)
		}
		return
	}
	// Фолбэк: локальная переменная.
	// ОБНОВЛЕНО В v8.0.1.
	if atomic.LoadInt32(&internalFallbackCounter) > 0 {
		atomic.AddInt32(&internalFallbackCounter, -1)
	}
}

// internalFallbackCounter — локальная атомарная переменная для фолбэка.
// Используется если маппинг `/dev/shm/` не инициализирован
// (например, в режиме одного процесса или при недоступности `/dev/shm/`).
// ОБНОВЛЕНО В v8.0.1: Заменяет `internalGoCounter` из Эксперимента №13.
var internalFallbackCounter int32

// ============================================================================
// ЧТЕНИЕ СЧЁТЧИКА: ОСНОВНОЙ ИНТЕРФЕЙС ДЛЯ TUI
// ============================================================================

// GetLiveBotsShmCount считывает текущее количество ботов, удерживаемых
// во ВСЕХ ловушках (порт 22 + мульти-ловушки).
//
// ТРИ УРОВНЯ ФОНБЭКА:
//  1. Если маппинг `/dev/shm/` инициализирован → читаем через `atomic.LoadInt32`
//  2. Если маппинг не инициализирован → пытаемся инициализировать как слейв
//  3. Если инициализация не удалась → сканируем `/proc/net/tcp` на порт 22
//
// ЗАДЕРЖКА:
//
//	Уровень 1: ~0 наносекунд (одна атомарная инструкция)
//	Уровень 3: ~1 миллисекунда (чтение двух файлов `/proc`)
//
// ОБНОВЛЕНО В v8.0.1: Восстановлена логика фолбэка из закомментированного кода.
// Счётчик показывает ОБЩЕЕ количество ботов во всех ловушках, не только порт 22.
func GetLiveBotsShmCount() int {
	if shmCounter != nil {
		// Основной путь: маппинг инициализирован, читаем атомарно.
		// ОБНОВЛЕНО В v8.0.1.
		return int(atomic.LoadInt32(shmCounter))
	}

	// Попытка инициализировать маппинг как слейв (если ещё не было сделано).
	// Это покрывает случай, когда `InitShmSlave()` не был вызван из `main.go`.
	// ОБНОВЛЕНО В v8.0.1.
	InitShmSlave()
	if shmCounter != nil {
		return int(atomic.LoadInt32(shmCounter))
	}

	// РЕЗЕРВНЫЙ СПАСАТЕЛЬНЫЙ КОНТУР:
	// Если демон ещё не создал файл в `/dev/shm/`, TUI не падает и не выдаёт
	// ложный 0, а опрашивает ядро напрямую через `/proc/net/tcp`.
	// ОБНОВЛЕНО В v8.0.1: Восстановлено из закомментированного кода.
	return GetActiveTrappedBotsCount()
}

