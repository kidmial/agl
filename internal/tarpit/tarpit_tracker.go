// InitShmMaster создаёт и инициализирует файл общей памяти в `/dev/shm/`.
// Вызывается ДЕМОНОМ (`--tarpit-daemon`) при старте, ПЕРЕД запуском воркеров.
//
// АЛГОРИТМ:
//  1. Удалить старый файл (если существует) — сброс счётчика при перезапуске
//  2. Создать новый файл размером 4 байта
//  3. Выполнить `syscall.Mmap` для маппирования файла в память процесса
//  4. Привести `[]byte` к `*int32` через `unsafe.Pointer`
//  5. Инициализировать счётчик значением 0 через `atomic.StoreInt32`
//
// ВАЖНО: `defer file.Close()` закрывает файловый дескриптор сразу после `Mmap`.
// Маппинг продолжает работать после закрытия файла, так как `Mmap` создаёт
// отдельное отображение в виртуальной памяти процесса. Это стандартный паттерн.
//
// ОБНОВЛЕНО В v8.0.1: Восстановлено из закомментированного кода.
// Вызывается из `StartTarpitManager()` перед запуском `StartManager()`.
func InitShmMaster() {
	// v8.0.3 (Аудит №2): НЕ удаляем файл. Удаление создавало новый inode,
	// и TUI с mmap старого inode навсегда читал застывшее значение.
	// Контракт: один стабильный inode на всю жизнь хоста.
	file, err := os.OpenFile(config.FileShm, os.O_RDWR|os.O_CREATE, 0666)
	if err != nil {
		return
	}
	defer file.Close()

	// Устанавливаем размер файла строго в 4 байта.
	// Это размер одного `int32` — наш счётчик ботов.
	// `syscall.Mmap` требует, чтобы файл имел ненулевой размер.
	if err := file.Truncate(4); err != nil {
		return
	}

	// Выполняем системный вызов `mmap` для маппирования файла в память процесса.
	// Параметры:
	//   - `int(file.Fd())` — файловый дескриптор
	//   - `0` — смещение от начала файла
	//   - `4` — размер маппинга (4 байта = один `int32`)
	//   - `PROT_READ|PROT_WRITE` — разрешение чтения и записи
	//   - `MAP_SHARED` — изменения видны всем процессам, маппировавшим файл
	//
	// ВАЖНО: `MAP_SHARED` гарантирует, что запись демона видна в TUI.
	// Если использовать `MAP_PRIVATE`, изменения не синхронизируются между процессами.
	//
	// ОБНОВЛЕНО В v8.0.1.
	data, err := syscall.Mmap(int(file.Fd()), 0, 4,
		syscall.PROT_READ|syscall.PROT_WRITE,
		syscall.MAP_SHARED)
	if err != nil {
		return
	}

	// Сохраняем маппированный байтовый срез в глобальную переменную.
	// Это предотвращает освобождение памяти сборщиком мусора.
	// ОБНОВЛЕНО В v8.0.1.
	shmData = data

	// Приводим первый байт `[]byte` к указателю на `*int32` через `unsafe.Pointer`.
	// Это стандартный паттерн для работы с маппированной памятью через атомарные операции.
	//
	// БЕЗОПАСНОСТЬ: `Mmap` гарантирует выравнивание на размер страницы (4096 байт),
	// что больше чем требуемое выравнивание `int32` (4 байта). Приведение безопасно.
	//
	// ОБНОВЛЕНО В v8.0.1.
	shmCounter = (*int32)(unsafe.Pointer(&shmData[0]))

	// Инициализируем счётчик значением 0 через атомарную запись.
	// Это гарантирует, что даже если файл был перезаписан, счётчик начнётся с 0.
	// ОБНОВЛЕНО В v8.0.1.
	atomic.StoreInt32(shmCounter, 0)
}

