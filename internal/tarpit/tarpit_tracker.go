// КОМПОНЕНТ: Высокоскоростной Межпроцессный Трекер Ботов (Нативный + Шм-Мост)
// ВЕРСИЯ: v8.0.1
// РОЛЬ: Обеспечивает подсчёт количества ботов, удерживаемых в Дегтярной Яме,
//
//	и передачу этого счётчика из демона в TUI через общую память.
//
// ============================================================================
//
// АРХИТЕКТУРНАЯ ПРОБЛЕМА, КОТОРУЮ РЕШАЕТ ЭТОТ ФАЙЛ:
//
//	В новой архитектуре единого демона (единый демон для всех ловушек):
//	- Демон (`agld_tarpit.service`) — отдельный процесс, держит все воркеры
//	- TUI — отдельный процесс, отображает счётчик ботов
//	Атомарная переменная в ОЗУ одного процесса НЕ видна другому процессу.
//	Нужен механизм МЕЖПРОЦЕССНОГО взаимодействия.
//
// РЕШЕНИЕ:
//
//	Используем высокоскоростной IPC-мост через `/dev/shm/amberguard.counter`
//	на базе системного вызова `syscall.Mmap`.
//	- Демон (мастер) создаёт файл и записывает в него счётчик через атомарные операции
//	- TUI (слейв) открывает файл и читает счётчик без блокировок и дискового ввода-вывода
//	Задержка чтения — 0 наносекунд, без вызовов `ss` или чтения файлов с диска.
//
// ТРИ УРОВНЯ ФОНБЭКА:
//  1. Основной: `/dev/shm/` через Mmap (наносекундная задержка)
//  2. Фолбэк: Атомарная переменная в ОЗУ (если демон и TUI в одном процессе)
//  3. Резерв: Сканирование `/proc/net/tcp` на порт 22 (если `/dev/shm/` недоступен)
//
// ### [2026-08-22] — Восстановление межпроцессного трекера (v8.0.1)
//   - Восстановлен механизм `/dev/shm/` через `syscall.Mmap`, закомментированный
//     как Эксперимент №13.
//   - `InitShmMaster()` создаёт файл в `/dev/shm/` и маппит 4 байта для записи.
//   - `InitShmSlave()` открывает существующий файл и маппит для чтения.
//   - `GetLiveBotsShmCount()` читает из общей памяти с фолбэком на резервное сканирование.
//   - Восстановлен `GetActiveTrappedBotsCount()` — сканирование `/proc/net/tcp`.
//   - Заменён временный атомарный счётчик на полноценный межпроцессный механизм.
//
// ============================================================================
