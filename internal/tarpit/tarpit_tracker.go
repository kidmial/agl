// RemoveShm зачищает маппинг и файл общей памяти при выключении ловушки.
// Вызывается при полной остановке демона (деактивация последней ловушки).
//
// АЛГОРИТМ:
//  1. Вызвать `syscall.Munmap` для освобождения маппинга из памяти процесса
//  2. Обнулить глобальные указатели
//  3. Удалить файл `/dev/shm/amberguard.counter`
//
// ОБНОВЛЕНО В v8.0.1: Восстановлено из закомментированного кода.
// Вызывается из `stopAllWorkers()` в `tarpit_manager.go` при завершении демона.
// RemoveShm освобождает маппинг при остановке демона.
// v8.0.3 (Аудит №2): файл НЕ удаляем — стабильный inode это контракт с TUI.
// Счётчик обнуляем ПЕРЕД отмаппингом, чтобы TUI видел честный 0.
func RemoveShm() {
	if shmCounter != nil {
		atomic.StoreInt32(shmCounter, 0)
	}
	if shmData != nil {
		_ = syscall.Munmap(shmData)
		shmData = nil
	}
	shmCounter = nil
}

