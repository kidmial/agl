// Глобальные указатели на маппированную память `/dev/shm/`.
// Эти переменные живут на протяжении всего жизненного цикла процесса.
//
// ВАЖНО: `shmData` держит ссылку на маппированный `[]byte`, чтобы
// сборщик мусора не освободил память, пока процесс жив.
// `shmCounter` — приведённый указатель на `*int32` для атомарных операций.
//
// ОБНОВЛЕНО В v8.0.1: Восстановлены из закомментированного кода Эксперимента №13.
var (
	shmData    []byte // Маппированный байтовый срез из `/dev/shm/`
	shmCounter *int32 // Указатель на 4-байтовый счётчик внутри `shmData`
)

// ============================================================================
// ИНИЦИАЛИЗАЦИЯ: МАСТЕР (ДЕМОН)
