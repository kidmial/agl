// КОМПОНЕНТ: Метаданные сборки комплекса (версия, время сборки)
// ВЕРСИЯ: v8.3.0 (Блок 5, задача 5.1)
// РОЛЬ: Единая точка правды о версии для TUI и CLI-ключей (--version/--info).
//
// АРХИТЕКТУРНАЯ ПОЗИЦИЯ:
//
//	Значения внедряются НА ЭТАПЕ КОМПИЛЯЦИИ через -ldflags:
//	  -X agl/internal/buildinfo.Version=$(VERSION)
//	  -X agl/internal/buildinfo.BuildTime=$(BUILD_TIME)
//	Сборка без ldflags (голый go build) оставляет дефолты "dev"/"unknown" —
//	это честный маркер «нерелизной» сборки, а не молчаливая подмена версии.
//
// КОНТРАКТ:
//   - Пакет без импортов и побочных эффектов: только две переменные.
//   - Не является целью i18n: версия — техническая строка, не пользовательский текст.
//
// ============================================================================
package buildinfo

// Version — семантическая версия комплекса.
// Переопределяется Makefile (VERSION ?= v8.3.0) через -ldflags при сборке.
var Version = "dev"

// BuildTime — UTC-метка момента сборки в формате RFC3339.
// Переопределяется Makefile через -ldflags; дефолт — маркер неизвестной сборки.
var BuildTime = "unknown"
